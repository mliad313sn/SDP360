-- Chunk 4B — reports.db config tables → PostgreSQL.
-- `sites` already created by 001_auth.sql (users.site_id FK). This migration
-- adds the remaining config tables. Idempotent (IF NOT EXISTS).
-- Recipe: AUTOINCREMENT->IDENTITY (INTEGER, matching 001_auth.sql sites/users);
-- created_at/updated_at DB-managed->TIMESTAMPTZ; details/JSON kept TEXT for
-- byte-identical round-trip; no FKs on audit_log (mirrors sqlite — audit rows
-- outlive their referents).

CREATE TABLE IF NOT EXISTS action_departments (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  sort_order  INTEGER DEFAULT 0,
  active      INTEGER DEFAULT 1,
  created_at  TIMESTAMPTZ DEFAULT now(),
  updated_at  TIMESTAMPTZ
);
-- Case-insensitive uniqueness (matches sqlite "name TEXT UNIQUE COLLATE NOCASE").
CREATE UNIQUE INDEX IF NOT EXISTS ux_action_departments_name_ci ON action_departments (lower(name));
CREATE INDEX IF NOT EXISTS idx_action_departments_active ON action_departments(active);

CREATE TABLE IF NOT EXISTS audit_log (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id   INTEGER,
  site_id     INTEGER,
  user_id     INTEGER,
  username    TEXT,
  action      TEXT NOT NULL,
  details     TEXT,
  created_at  TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_al_report ON audit_log(report_id);
CREATE INDEX IF NOT EXISTS idx_al_site   ON audit_log(site_id);
CREATE INDEX IF NOT EXISTS idx_al_time   ON audit_log(created_at);

CREATE TABLE IF NOT EXISTS dashboard_preset_groups (
  scope         TEXT NOT NULL,
  preset_name   TEXT NOT NULL,
  group_name    TEXT NOT NULL,
  display_order INTEGER DEFAULT 0,
  updated_at    TIMESTAMPTZ DEFAULT now(),
  updated_by    TEXT,
  PRIMARY KEY (scope, preset_name, group_name)
);
CREATE INDEX IF NOT EXISTS idx_dpg_scope ON dashboard_preset_groups(scope);
CREATE INDEX IF NOT EXISTS idx_dpg_group ON dashboard_preset_groups(scope, group_name);
