-- reports.db Sub-chunk A — auth/sessions schema. sites→users→user_roles→sessions
-- (FK order). Type-preserving: active INTEGER, AUTOINCREMENT→IDENTITY, DB-managed
-- timestamps TIMESTAMPTZ, session timestamps TIMESTAMPTZ (login writes ISO strings
-- → pg coerces). Real FKs incl. ON DELETE CASCADE. Idempotent.
CREATE TABLE IF NOT EXISTS sites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT UNIQUE NOT NULL,
  zoho_group TEXT,
  active INTEGER DEFAULT 1,
  sort_order INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  full_name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  site_id INTEGER REFERENCES sites(id),
  role TEXT DEFAULT 'editor',
  active INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT now(),
  -- Entra ID SSO (mirrors the sqlite ALTERs added 2026-07): email is the
  -- pre-provisioning match key; entra_oid links on first Microsoft login;
  -- first/last/title/office auto-sync FROM Entra on each SSO login.
  email      TEXT,
  entra_oid  TEXT,
  first_name TEXT,
  last_name  TEXT,
  title      TEXT,
  office     TEXT
);
-- Same columns for PG databases created BEFORE the SSO work (this file is
-- re-applied idempotently at every boot via initPgReports).
ALTER TABLE users ADD COLUMN IF NOT EXISTS email      TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS entra_oid  TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS first_name TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_name  TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS title      TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS office     TEXT;
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_entra ON users(entra_oid);
CREATE TABLE IF NOT EXISTS user_roles (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL,
  granted_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (user_id, role)
);
CREATE INDEX IF NOT EXISTS idx_ur_user ON user_roles(user_id);
CREATE INDEX IF NOT EXISTS idx_ur_role ON user_roles(role);
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now(),
  last_seen  TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_sessions_user    ON sessions(user_id);
CREATE INDEX IF NOT EXISTS ix_sessions_expires ON sessions(expires_at);
