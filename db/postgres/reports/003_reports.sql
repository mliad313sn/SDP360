-- Chunk 4C — reports.db report-editor tables → PostgreSQL. Idempotent (IF NOT EXISTS).
-- sites already created by 001_auth.sql. INTEGER IDENTITY to match 001/002.
-- created_at/updated_at DB-managed → TIMESTAMPTZ; app dates (start_date/end_date/
-- submitted_at/due_date/fetched_at) → TEXT; JSON blob cols → TEXT (byte-identical
-- round-trip); sqlite REAL → double precision. Includes the ALTER-added columns
-- (weekly_reports.created_by, action_items.department/comment).

CREATE TABLE IF NOT EXISTS weeks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year INTEGER NOT NULL, week_number INTEGER NOT NULL,
  start_date TEXT NOT NULL, end_date TEXT NOT NULL, label TEXT NOT NULL,
  UNIQUE(year, week_number)
);

CREATE TABLE IF NOT EXISTS weekly_reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id INTEGER NOT NULL REFERENCES sites(id),
  week_id INTEGER NOT NULL REFERENCES weeks(id),
  status TEXT DEFAULT 'draft', submitted_at TEXT, submitted_by INTEGER,
  created_by INTEGER,
  created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(site_id, week_id)
);

CREATE TABLE IF NOT EXISTS infra_kpis (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id INTEGER NOT NULL REFERENCES weekly_reports(id) ON DELETE CASCADE,
  service TEXT NOT NULL, kpi TEXT NOT NULL, target TEXT,
  status_value TEXT, status_color TEXT DEFAULT 'green', trend TEXT DEFAULT 'stable',
  sort_order INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS helpdesk_data (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id INTEGER NOT NULL UNIQUE REFERENCES weekly_reports(id) ON DELETE CASCADE,
  time_to_assign double precision, time_to_assign_prev double precision,
  first_reply double precision, first_reply_prev double precision,
  resolution_time double precision, resolution_time_prev double precision,
  closing_time double precision, closing_time_prev double precision,
  comments_metrics TEXT, comments_sla TEXT, tech_on_break TEXT, techs_on_duty TEXT,
  sla_violations TEXT, group_metrics TEXT, all_groups TEXT, selected_group TEXT,
  chart_data TEXT, fetched_at TEXT, updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lights (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id INTEGER NOT NULL REFERENCES weekly_reports(id) ON DELETE CASCADE,
  type TEXT NOT NULL, content TEXT NOT NULL, sort_order INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS action_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id INTEGER NOT NULL REFERENCES weekly_reports(id) ON DELETE CASCADE,
  task TEXT NOT NULL, priority TEXT DEFAULT 'Medium', due_date TEXT, owner TEXT,
  status TEXT DEFAULT 'open', sort_order INTEGER DEFAULT 0,
  department TEXT, comment TEXT,
  uid TEXT, source TEXT, origin_id INTEGER,  -- SP1b: stable id + cross-source merge link
  lineage TEXT                               -- SP1b-lignée: carry-forward chain root
);

CREATE TABLE IF NOT EXISTS monthly_reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id INTEGER NOT NULL REFERENCES sites(id), year INTEGER NOT NULL, month INTEGER NOT NULL,
  edited_lights TEXT, edited_actions TEXT, notes TEXT, status TEXT DEFAULT 'draft',
  updated_at TIMESTAMPTZ DEFAULT now(), UNIQUE(site_id, year, month)
);

CREATE TABLE IF NOT EXISTS annual_objectives (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id INTEGER NOT NULL REFERENCES sites(id), year INTEGER NOT NULL,
  objective TEXT NOT NULL, target TEXT, status TEXT DEFAULT 'in_progress',
  sort_order INTEGER DEFAULT 0, updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ao_site_year ON annual_objectives(site_id, year);

CREATE TABLE IF NOT EXISTS site_module_codes (
  site_id INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
  module TEXT NOT NULL, code TEXT NOT NULL, updated_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (site_id, module)
);
CREATE INDEX IF NOT EXISTS idx_smc_module ON site_module_codes(module);
CREATE INDEX IF NOT EXISTS idx_smc_code ON site_module_codes(code);

CREATE TABLE IF NOT EXISTS infra_kpi_catalog (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service TEXT NOT NULL, kpi TEXT NOT NULL, target_default TEXT,
  display_order INTEGER DEFAULT 0, active INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT now(), UNIQUE(service, kpi)
);
CREATE INDEX IF NOT EXISTS idx_infra_kpi_cat_service ON infra_kpi_catalog(service);
