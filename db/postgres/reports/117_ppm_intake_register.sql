-- Immutable once given: an UPDATE may set a NULL ref (creation path / backfill), never change or clear a set one.
CREATE OR REPLACE FUNCTION sdp_project_ref_immutable() RETURNS trigger AS $$
BEGIN
  IF OLD.project_ref IS NOT NULL AND NEW.project_ref IS DISTINCT FROM OLD.project_ref THEN
    RAISE EXCEPTION 'project_ref is immutable (% cannot become %)', OLD.project_ref, COALESCE(NEW.project_ref, 'NULL');
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'portfolio_projects_ref_immutable') THEN
    CREATE TRIGGER portfolio_projects_ref_immutable BEFORE UPDATE OF project_ref ON portfolio_projects FOR EACH ROW EXECUTE FUNCTION sdp_project_ref_immutable();
  END IF;
END $$;

-- One counter per creation year. Only ever incremented (INSERT … ON CONFLICT DO UPDATE … RETURNING, row-locked, so two
-- concurrent creations never share a number); nothing decrements it, so a deleted or purged project never frees its number.
CREATE TABLE IF NOT EXISTS ppm_project_ref_seq (
  year    INTEGER PRIMARY KEY CHECK (year BETWEEN 1970 AND 2200),
  last_n  INTEGER NOT NULL CHECK (last_n >= 0)
);

-- Portfolio reference lists (spec §19). A value is never physically deleted: it is retired (active = 0, retired_at),
-- so projects that carry it keep reading its label. `code` is immutable (the stored value); labels, colour, order,
-- default and active are editable by the admin tier. proposed = 1: the value or its meaning encodes business policy
-- (priority meaning, risk levels, effort bands) that is NOT approved — shown with a "proposed, not approved" mark.
-- Locked domains (project_status, decision_required, schedule_confidence) mirror codes the application logic reads:
-- labels / colour / order only, no new code, no retirement (services/ppm/portfolioLookups.js LOCKED).
-- colour = a brand token name, never a raw colour value (public/_tokens.css).
CREATE TABLE IF NOT EXISTS ppm_lookup_values (
  id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  domain         TEXT NOT NULL CHECK (domain IN ('project_type', 'priority', 'budget_status', 'project_status', 'decision_required', 'delivery_effort', 'risk_exposure', 'schedule_confidence')),
  code           TEXT NOT NULL CHECK (code ~ '^[a-z0-9][a-z0-9_]{0,39}$'),
  label_en       TEXT NOT NULL,
  label_fr       TEXT NOT NULL,
  description_en TEXT,
  description_fr TEXT,
  color          TEXT CHECK (color IS NULL OR color IN ('slate', 'blue', 'teal', 'green', 'amber', 'orange', 'red', 'grey')),
  sort_order     INTEGER NOT NULL DEFAULT 0,
  is_default     SMALLINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
  proposed       SMALLINT NOT NULL DEFAULT 0 CHECK (proposed IN (0, 1)),
  active         SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  retired_at     TEXT,
  retired_by     INTEGER,
  updated_at     TEXT,
  updated_by     TEXT,
  UNIQUE (domain, code)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ppm_lookup_default ON ppm_lookup_values (domain) WHERE is_default = 1 AND active = 1;

