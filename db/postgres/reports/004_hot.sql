-- Chunk 4D-1 — reports.db hot-path (Zoho-synced) tables → PostgreSQL. Idempotent.
-- INTEGER IDENTITY; time_elapsed_ms BIGINT; overall_score double precision;
-- app dates + JSON → TEXT; flags/counts INTEGER. UNIQUE on Zoho-id cols. No FKs
-- between hot tables (soft-linked by Zoho ids; sync order not guaranteed).
-- Includes ALTER-added cols: change_records.{group_name,stage_status},
-- request_records.{request_type,mode,impact,udf_json}, sync_metadata.{last_full_sync_at,
-- schema_snapshot,deleted_count}.

CREATE TABLE IF NOT EXISTS sync_metadata (
  job_name          TEXT PRIMARY KEY,
  last_sync_at      TEXT, last_sync_rows INTEGER DEFAULT 0,
  last_error        TEXT, last_error_at  TEXT, sync_count INTEGER DEFAULT 0,
  last_full_sync_at TEXT, schema_snapshot TEXT, deleted_count INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS change_records (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  change_id TEXT UNIQUE NOT NULL, display_id TEXT, subject TEXT, status TEXT, stage TEXT,
  stage_status TEXT, risk TEXT, change_type TEXT, emergency INTEGER DEFAULT 0,
  category TEXT, sub_category TEXT, requester TEXT, requester_id TEXT, owner_id TEXT,
  manager TEXT, site_id TEXT, group_id TEXT, group_name TEXT, scheduled_start TEXT,
  scheduled_end TEXT, completed_time TEXT, created_time TEXT, closure_code TEXT,
  udf_json TEXT, fetched_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_cr_created ON change_records(created_time);
CREATE INDEX IF NOT EXISTS idx_cr_status  ON change_records(status);
CREATE INDEX IF NOT EXISTS idx_cr_site    ON change_records(site_id);

CREATE TABLE IF NOT EXISTS cab_approvals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  approval_id TEXT UNIQUE NOT NULL, change_id TEXT NOT NULL, approver_name TEXT,
  approval_status TEXT, approval_stage TEXT, approval_level TEXT, approval_level_status TEXT,
  recommendation_requested TEXT, action_taken_on TEXT, turnaround_minutes INTEGER,
  rule_type TEXT, comments TEXT, fetched_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_cab_change ON cab_approvals(change_id);
CREATE INDEX IF NOT EXISTS idx_cab_status ON cab_approvals(approval_status);

CREATE TABLE IF NOT EXISTS survey_results (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id TEXT UNIQUE NOT NULL, response_id TEXT, survey_id TEXT, survey_name TEXT,
  request_id TEXT, request_display_id TEXT, change_id TEXT, user_id TEXT,
  overall_score double precision, survey_sent_on TEXT, survey_responded_on TEXT, fetched_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_sr_request ON survey_results(request_display_id);
CREATE INDEX IF NOT EXISTS idx_sr_change  ON survey_results(change_id);
CREATE INDEX IF NOT EXISTS idx_sr_sent    ON survey_results(survey_sent_on);

CREATE TABLE IF NOT EXISTS survey_answers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  response_id TEXT NOT NULL, result_id TEXT NOT NULL, question_id TEXT, question_text TEXT,
  question_type TEXT, answer_text TEXT, answer_option TEXT, score INTEGER,
  skipped INTEGER DEFAULT 0, fetched_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_sa_response ON survey_answers(response_id);
CREATE INDEX IF NOT EXISTS idx_sa_result   ON survey_answers(result_id);

CREATE TABLE IF NOT EXISTS request_records (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id TEXT UNIQUE NOT NULL, display_id TEXT, subject TEXT, request_status TEXT,
  pending_status INTEGER DEFAULT 1, overdue_status INTEGER DEFAULT 0, request_type TEXT,
  service_request INTEGER DEFAULT 0, is_escalated INTEGER DEFAULT 0, reopen_count INTEGER DEFAULT 0,
  due_by_time TEXT, time_elapsed_ms BIGINT, created_time TEXT, resolved_time TEXT,
  completed_time TEXT, responded_time TEXT, assigned_time TEXT, last_updated_time TEXT,
  first_response_overdue TEXT, technician TEXT, requester TEXT, category TEXT, sub_category TEXT,
  site TEXT, tech_group TEXT, mode TEXT, impact TEXT, udf_json TEXT, fetched_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_rr_created ON request_records(created_time);
CREATE INDEX IF NOT EXISTS idx_rr_status  ON request_records(request_status);
CREATE INDEX IF NOT EXISTS idx_rr_site    ON request_records(site);
CREATE INDEX IF NOT EXISTS idx_rr_pending ON request_records(pending_status);
CREATE INDEX IF NOT EXISTS idx_rr_overdue ON request_records(overdue_status);
