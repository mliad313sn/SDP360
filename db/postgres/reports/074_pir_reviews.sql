-- E-I03 (audit I-03, catalogue R15) — one post-incident (PIR) review record per major incident.
-- decisions, a before/after window (days) and the counts of same category × sub-category incidents on the site
-- before / after the incident (NULL = not measured yet, e.g. the after-window has not elapsed; frozen at sign-off),
-- the linked commitment ids, the author, and a sign-off by ANOTHER person (recorded human act, never automatic).
-- Used only while report_config pir_reviews_enabled = '1' (default '0'). ADDITIVE and idempotent.
CREATE TABLE IF NOT EXISTS pir_reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id TEXT NOT NULL UNIQUE,
  site_id INTEGER,
  category TEXT, sub_category TEXT, occurred_on TEXT,
  decisions TEXT,
  window_days INTEGER NOT NULL DEFAULT 90,
  before_count INTEGER, after_count INTEGER, counted_at TEXT,
  commitment_ids TEXT NOT NULL DEFAULT '[]',
  author_id INTEGER, author TEXT,
  created_at TEXT, updated_at TEXT,
  signed_off_by INTEGER, signed_off_name TEXT, signed_off_at TEXT, signoff_note TEXT,
  version INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_pir_reviews_site ON pir_reviews(site_id);
