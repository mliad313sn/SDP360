'use strict';
// E-S06 (prep for audit S-10) — retention inventory generated FROM CODE.
//
//   node tools/security/retention-inventory.js           writes docs/ops/RETENTION-INVENTORY.md
//   node tools/security/retention-inventory.js --check   exits 1 when the committed file is stale
//
// One row per object type: table → what the code does TODAY (deletion / expiry) → duration and the config key or
// variable that drives it → owner. The owner is UNKNOWN everywhere and so are legal durations: a DPO / legal
// decision fills them, this tool never invents one. Rows for soft-deletable tables come from
// services/softDelete.TABLES, so a table added there appears here without editing this file.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'docs', 'ops', 'RETENTION-INVENTORY.md');

/** Hand-declared rows; `source` must exist (checked by the test) so a moved file makes the row visibly stale. */
const DECLARED = Object.freeze([
  { object: 'Security / audit log', table: 'system_log', today: 'purged nightly by job audit.retention: ordinary rows older than the window; risk and governance categories kept longer (never below 84 months)', duration: '12 months (ordinary) · 84 months (risk, governance)', key: 'env AUDIT_RETENTION_MONTHS, AUDIT_RISK_RETENTION_MONTHS', source: 'reports-db.js' },
  { object: 'Sessions', table: 'sessions', today: 'refused after expires_at; deleted at logout / force logout / deactivation of the account', duration: 'session lifetime set at login', key: '— (code)', source: 'reports-db.js' },
  { object: 'Teams SLA alert anti-duplicate log', table: 'sla_alert_log', today: 'purged by the poller', duration: '90 days', key: '— (code: poll-sla purge(90))', source: 'services/slaAlertLog.js' },
  { object: 'Field outbox ledger', table: 'field_outbox', today: 'purged nightly by job field.purge', duration: '90 days', key: '— (code)', source: 'services/fieldStore.js' },
  { object: 'Field chunked uploads (abandoned)', table: 'field_uploads, field_chunks', today: 'open uploads purged nightly by job field.purge', duration: '48 hours', key: '— (code)', source: 'services/fieldStore.js' },
  { object: 'Share links', table: 'share_links, share_views', today: 'a link expires at its end date or when revoked; rows are kept (no purge)', duration: 'per link', key: '— (set per link)', source: 'db/postgres/reports/019_reports_engagement.sql' },
  { object: 'Commitment evidence', table: 'evidence_items', today: 'kept; carries a retention_class column (default standard) that nothing reads yet; no archive event', duration: 'UNKNOWN', key: '— (retention_class not enforced)', source: 'db/postgres/reports/021_commitments.sql' },
  { object: 'Access grants and requests', table: 'access_grants, access_requests, access_request_events', today: 'a grant ends at valid_to (job access.grant_expiry when armed); rows are kept, events are append-only', duration: 'per grant', key: 'access_grant_expiry_job', source: 'services/accessStore.js' },
  { object: 'Access recertification', table: 'access_recert_campaigns, access_recert_lines', today: 'kept; nothing is deleted', duration: 'UNKNOWN', key: 'access_recert_enabled', source: 'db/postgres/reports/068_access_recert.sql' },
  { object: 'Database backups', table: '(files) <data>/backups', today: 'nightly dump; older dumps beyond the kept count are removed', duration: '14 dumps', key: 'env SDP_BACKUP_KEEP, SDP_BACKUP_DIR', source: 'services/backup.js' },
  { object: 'Inspection photos and signatures', table: '(files) <data>/blobs/inspection/<id>', today: 'removed with the inspection (hard delete) or by softdelete.purge when soft delete is on', duration: 'follows the inspection', key: 'soft_delete_enabled, soft_delete_purge_enabled', source: 'services/blobStore.js' },
]);

function rows() {
  const sd = require('../../services/softDelete');
  const soft = Object.keys(sd.TABLES).sort().map((t) => ({
    object: 'Soft-deletable record', table: t,
    today: 'hard delete while soft_delete_enabled = 0 (today); when 1, stamped deleted_at and restorable, then hard-deleted by job softdelete.purge only if soft_delete_purge_enabled = 1',
    duration: `${sd.DEFAULT_RETENTION_DAYS} days after the stamp (PROPOSED A-19 value, not approved)`, key: 'soft_delete_enabled, soft_delete_retention_days, soft_delete_purge_enabled', source: 'services/softDelete.js',
  }));
  return [...soft, ...DECLARED];
}

const cell = (v) => String(v == null ? '' : v).replace(/\|/g, '\\|');

function render() {
  const L = [];
  L.push('# Retention inventory — generated from code', '');
  L.push('PROPOSITION — TO BE FILLED BY A PERSON. Generated by `node tools/security/retention-inventory.js` (E-S06, prep for audit S-10).');
  L.push('Do not edit by hand: `--check` fails when this file differs from the code. The **owner** and the **legal duration** columns are');
  L.push('UNKNOWN on purpose — they are decisions of the data protection officer / legal owner, including any legal hold. "Today" describes');
  L.push('what the code does now; it is not a policy.', '');
  L.push('| Object | Table / store | Today\'s deletion / expiry behaviour | Duration in code | Config key / variable | Code | Owner | Legal duration / hold |');
  L.push('|---|---|---|---|---|---|---|---|');
  for (const r of rows()) L.push(`| ${cell(r.object)} | \`${cell(r.table)}\` | ${cell(r.today)} | ${cell(r.duration)} | ${cell(r.key)} | \`${cell(r.source)}\` | UNKNOWN | UNKNOWN |`);
  L.push('', 'Questions for the owner (one answer per row): how long must this be kept, who may shorten it, is any row under legal hold, and');
  L.push('what proves the deletion happened (the jobs above already log a row in system_log or the sync run log).');
  return L.join('\n') + '\n';
}

module.exports = { DECLARED, rows, render, OUT };

if (require.main === module) {
  const md = render();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== md) { console.error('RETENTION-INVENTORY.md is stale — run: node tools/security/retention-inventory.js'); process.exitCode = 1; }
    else console.log('RETENTION-INVENTORY.md is up to date.');
  } else { fs.writeFileSync(OUT, md); console.log('wrote ' + path.relative(ROOT, OUT)); }
}
