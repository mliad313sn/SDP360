const ident = (s) => { if (!/^[a-z_][a-z0-9_]{0,62}$/i.test(String(s))) throw new Error(`not a valid PostgreSQL name: ${s}`); return String(s); };
/** Candidate .env files of a previous SDP on this machine (the folder itself, then renamed copies `<dir>.old-*`). */
function previousEnvFiles() {
  const out = [];
  if (process.env.SDP_SETUP_PREV_ENV) out.push(process.env.SDP_SETUP_PREV_ENV);
  out.push(path.join(DIR, '.env'));
  const parent = path.dirname(DIR), base = path.basename(DIR).toLowerCase();
  try {
    for (const n of fs.readdirSync(parent).sort().reverse()) {
      const l = n.toLowerCase();
      if (l !== base && l.startsWith(base) && /\.(old|bak|backup)/.test(l)) out.push(path.join(parent, n, '.env'));
    }
  } catch (_) {}
  return out.filter((f, k) => out.indexOf(f) === k && fs.existsSync(f));
}
/** The 4MyPeople installer's standard superuser password (same lookup as tools/pg/provision-prod.js). Never logged. */
function fourMyPeoplePassword() {
  const c = [];
  if (process.env.FMP_CONFIG_PSD1) c.push(process.env.FMP_CONFIG_PSD1);
  if (process.env.TEMP) c.push(path.join(process.env.TEMP, '4MyPeople-Installer', 'config.psd1'));
  try { for (const u of fs.readdirSync('C:\\Users')) c.push(path.join('C:\\Users', u, 'AppData', 'Local', 'Temp', '4MyPeople-Installer', 'config.psd1')); } catch (_) {}
  for (const f of c) { try { const m = fs.readFileSync(f, 'utf8').match(/StandardPgSuperPassword\s*=\s*'([^']+)'/); if (m) return m[1]; } catch (_) {} }
  return '';
}
/**
 * Role + database through the pg driver (from the freshly installed node_modules): no psql needed.
 * The superuser password is OPTIONAL. In order: (1) the application account of a previous SDP on this machine,
 * reused as is when it can already open the database — no superuser at all; (2) the password typed in Setup /
 * SDP_SETUP_PGSUPERPASS; (3) the 4MyPeople standard password; (4) no password (trust/peer). Returns the
 * application password to write in .env.
 */
async function createDatabase(d) {
  const { Client } = require(path.join(DIR, 'node_modules', 'pg'));
  const host = arg('--pg-host', 'localhost'), port = Number(arg('--pg-port', '5432')), db = ident(arg('--db-name', 'sdp_dashboard')), user = ident(arg('--db-user', 'sdp_app'));
  for (const f of previousEnvFiles()) {
    let u; try { u = new URL(readEnv(f).PG_URL || ''); } catch (_) { continue; }
    if (decodeURIComponent(u.username) !== user || u.pathname.slice(1) !== db) continue;
    const pass = decodeURIComponent(u.password);
    const c = new Client({ host, port, user, password: pass, database: db });
    try { await c.connect(); await c.end(); log(`PostgreSQL: reusing the existing ${user} account and database ${db} of the previous installation (${f}) — no superuser needed`); return pass; }
    catch (_) { try { await c.end(); } catch (__) {} }
  }
  const tries = [process.env.SDP_SETUP_PGSUPERPASS, fourMyPeoplePassword(), ''].filter((p, k, a) => p != null && a.indexOf(p) === k);
  let c = null, last = null;
  for (const pw of tries) {
    const t = new Client({ host, port, user: 'postgres', password: pw, database: 'postgres' });
    try { await t.connect(); c = t; break; } catch (e) { last = e; try { await t.end(); } catch (_) {} }
  }
  if (!c) throw new Error(`cannot create the database: no previous SDP account works and the PostgreSQL superuser login failed (${last && last.message}). Type the postgres password in Setup or set SDP_SETUP_PGSUPERPASS`);
  try {
    const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";
    const role = await c.query('SELECT 1 FROM pg_roles WHERE rolname = $1', [user]);
    // a new installation owns its credentials: an existing role gets the new password written to .env
    await c.query(`${role.rowCount ? 'ALTER' : 'CREATE'} ROLE "${user}" LOGIN PASSWORD ${lit(d._appPass)}`);
    const exists = await c.query('SELECT 1 FROM pg_database WHERE datname = $1', [db]);
    if (!exists.rowCount) await c.query(`CREATE DATABASE "${db}" OWNER "${user}" ENCODING 'UTF8' TEMPLATE template0`);
    log(`PostgreSQL: role ${user} ${role.rowCount ? 'updated' : 'created'}, database ${db} ${exists.rowCount ? 'already there (kept)' : 'created'}`);
  } finally { await c.end(); }
  return d._appPass;
}

function firewallRuleNames(port) { return { allow: `SDP Dashboard ${port} - loopback only`, block: `SDP Dashboard ${port} - block remote` }; }
function firewallCommands(port) {
  const n = firewallRuleNames(port);
  return [
    ['advfirewall', 'firewall', 'delete', 'rule', `name=${n.allow}`],
    ['advfirewall', 'firewall', 'delete', 'rule', `name=${n.block}`],
    ['advfirewall', 'firewall', 'add', 'rule', `name=${n.allow}`, 'dir=in', 'action=allow', 'protocol=TCP', `localport=${port}`, 'remoteip=127.0.0.1', 'profile=any'],
    ['advfirewall', 'firewall', 'add', 'rule', `name=${n.block}`, 'dir=in', 'action=block', 'protocol=TCP', `localport=${port}`, 'remoteip=any', 'profile=any'],
  ];
}
function firewall(port, { remove = false } = {}) {
  if (process.platform !== 'win32') return;
  const cmds = firewallCommands(port);
  for (const c of cmds.slice(0, 2)) spawnSync('netsh', c, { encoding: 'utf8' });
  if (remove) { log(`firewall rules for port ${port} removed`); return; }
  for (const c of cmds.slice(2)) {
    const r = spawnSync('netsh', c, { encoding: 'utf8' });
    if (r.status !== 0) { log(`firewall rule not applied (${(r.stderr || r.stdout || '').trim()}) — run as Administrator: netsh ${c.join(' ')}`); return; }
  }
  log(`firewall: TCP ${port} allowed from 127.0.0.1 only, blocked from the network (IIS is the sole entry point)`);
}

const SVC_EXE = () => path.join(DIR, 'service', 'SdpDashboardService.exe');
function serviceKind(env) {
  const want = arg('--service', 'auto');
  if (want === 'windows' || want === 'pm2') return want;
  if (env.SDP_SERVICE === 'windows' || env.SDP_SERVICE === 'pm2') return env.SDP_SERVICE;
  // a server already running the dashboard under pm2 stays on pm2 until an administrator moves it
  const j = spawnSync('pm2', ['jlist'], { encoding: 'utf8', shell: process.platform === 'win32' });
  try { if (j.status === 0 && JSON.parse(j.stdout || '[]').some((p) => p.name === (env.PM2_NAME || 'endeavour-dashboard'))) return 'pm2'; } catch (_) { /* no pm2 */ }
  return 'windows';
}
/** How the version already on disk was run: its own SDP_SERVICE, else pm2 (versions before the Windows service). */
/**
 * How to run the version that is back after a rollback. A 1.x application ships native modules (better-sqlite3)
 * built for the server's own Node.js: it cannot run on the Node.js bundled with this Setup, whatever SDP_SERVICE
 * says (a failed earlier Setup wrote SDP_SERVICE=windows into the .env it kept — field incident 2026-11-02).
 */
function previousServiceKind(env, dir) {
  try {
    const v = JSON.parse(fs.readFileSync(path.join(dir || DIR, 'package.json'), 'utf8')).version || '';
    if (/^[01]\./.test(v)) return 'pm2';
  } catch (_) { /* no package.json — fall back on the .env */ }
  if (env.SDP_SERVICE === 'windows' || env.SDP_SERVICE === 'pm2') return env.SDP_SERVICE;
  return 'pm2';
}
/** A 1.x (or older) application tree: same rule as previousServiceKind. Unset *_BACKEND meant sqlite there. */
function isLegacyTree(dir) {
  try { return /^[01]\./.test(JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version || ''); } catch (_) { return false; }
}
const LEGACY_MODULES = [
  ['assets', 'ASSETS_BACKEND', false], ['reports', 'REPORTS_BACKEND', false],
  ['tracker', 'TRACKER_BACKEND', true], ['meetings', 'MEETINGS_BACKEND', true], ['inspection', 'INSPECTION_BACKEND', true],
];
/**
 * Pure (A-01): does the installation still keep data in SQLite? 2.0 reads PostgreSQL only and ignores *_BACKEND,
 * so a module still on sqlite would silently start on an empty schema. Driven by the flag (unset on a 1.x tree =
 * sqlite, the 1.x default); a .db file is only evidence — a module on postgres with a .db = a frozen archive (warn).
 * Never reads a file's contents.
 */
function legacyStoreProblems({ env = {}, dir, legacy, exists = fs.existsSync }) {
  const refuse = [], warn = [];
  const dataDir = env.SDP_DATA_DIR ? path.resolve(dir, env.SDP_DATA_DIR) : path.join(dir, 'data');
  for (const [name, key, rootLegacy] of LEGACY_MODULES) {
    const raw = env[key] == null || String(env[key]).trim() === '' ? null : String(env[key]).trim();
    const backend = raw ? raw.toLowerCase() : (legacy ? 'sqlite' : 'postgres');
    const files = [path.join(dataDir, name + '.db'), ...(rootLegacy ? [path.join(dir, name + '.db')] : [])].filter((f) => exists(f));
    if (backend !== 'postgres') {
      refuse.push(`${name.toUpperCase()} still reads SQLite (${key}=${raw || 'unset, 1.x default sqlite'})${files.length ? ' — data in ' + files.join(', ') : ''}`);
    } else {
      for (const f of files) warn.push(`${f} is a frozen archive, kept, never read by 2.0`);
    }
  }
  return { refuse, warn };
}
/** Before ANY change (A-01): refuse an installation whose data still lives in SQLite, unless the operator overrides it. */
function preflight(envFile) {
  if (!fs.existsSync(envFile)) return;            // a fresh machine: nothing to protect
  const { refuse, warn } = legacyStoreProblems({ env: readEnv(envFile), dir: DIR, legacy: isLegacyTree(DIR) });
  for (const w of warn) log('legacy store: ' + w);
  if (!refuse.length) return;
  if (has('--ignore-legacy-store')) { for (const r of refuse) log('legacy store: ' + r); log('legacy store check overridden by the operator (--ignore-legacy-store)'); return; }
  throw new Error(`legacy data store: ${refuse.join('; ')}. Nothing was changed. See docs/UPGRADE-1x-to-2.0.md`);
}
/** The last lines of today's service log, and its first fatal line — so the setup log says WHY the service did not answer. */
function serviceLogTail(n = 40) {
  try {
    const dir = path.join(DIR, 'logs');
    const f = fs.readdirSync(dir).filter((x) => /^service-\d{8}\.log$/.test(x)).sort().pop();
    if (!f) return { file: null, tail: '', cause: '' };
    const lines = fs.readFileSync(path.join(dir, f), 'utf8').split(/\r?\n/);
    const tail = lines.slice(-n).join('\n');
    const cause = (lines.slice(-200).reverse().find((l) => /FATAL|^Error|Error:|ECONNREFUSED|EADDRINUSE|password authentication failed|Cannot find module/.test(l)) || '').trim();
    return { file: f, tail, cause };
  } catch (_) { return { file: null, tail: '', cause: '' }; }
}
function registerService(kind, env) {
  const S = require(path.join(ROOT, 'services', 'serviceControl'));
  const e = { ...env, SDP_SERVICE: kind };
  if (kind === 'windows') {
    if (process.platform !== 'win32') { log('Windows service: skipped (not Windows)'); return; }
    if (!fs.existsSync(SVC_EXE())) throw new Error('service\\SdpDashboardService.exe is missing from the installation');
    const acct = arg('--service-account', '');
    sh(SVC_EXE(), ['install', ...(acct ? ['--account', acct] : [])], { env: { SDP_SETUP_SVCPASS: process.env.SDP_SETUP_SVCPASS || '' }, shell: false });
    const st = S.status(e);
    if (st.state === 'running') { log('restarting the Windows service (stop → wait → start)'); S.restart(e); }
    else { log('starting the Windows service'); S.start(e); }
    return;
  }
  // pm2 (historical servers): register or stop → start, never reload
  const name = env.PM2_NAME || 'endeavour-dashboard';
  const list = spawnSync('pm2', ['jlist'], { encoding: 'utf8', shell: process.platform === 'win32' });
  let known = false; try { known = JSON.parse(list.stdout || '[]').some((p) => p.name === name); } catch (_) { /* pm2 missing */ }
  if (known) S.restart(e);
  else { sh('pm2', ['start', 'server.js', '--name', name, '--node-args=--max-old-space-size=4096']); }
  sh('pm2', ['save']);
}
function unregisterService(env) {
  if (fs.existsSync(SVC_EXE())) { try { sh(SVC_EXE(), ['uninstall'], { shell: false }); } catch (e) { log('service removal: ' + e.message); } }
  const name = env.PM2_NAME || 'endeavour-dashboard';
  const j = spawnSync('pm2', ['jlist'], { encoding: 'utf8', shell: process.platform === 'win32' });
  try { if (j.status === 0 && JSON.parse(j.stdout || '[]').some((p) => p.name === name)) { spawnSync('pm2', ['delete', name], { shell: process.platform === 'win32' }); spawnSync('pm2', ['save'], { shell: process.platform === 'win32' }); log('pm2 process removed'); } } catch (_) { /* no pm2 */ }
}

function iisFrontEnd(port) {
  const host = arg('--public-host', '');
  if (!host) return;
  if (process.platform !== 'win32') return;
  const ps = path.join(ROOT, 'tools', 'installer-v2', 'iis-setup.ps1');
  if (!fs.existsSync(ps)) { log('IIS: iis-setup.ps1 missing — skipped'); return; }
  const r = spawnSync('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', ps, '-HostName', host, '-Port', String(port), '-AppDir', DIR, '-Thumbprint', arg('--cert-thumbprint', ''), '-MsiDir', arg('--prereq-dir', '')], { encoding: 'utf8' });
  fs.appendFileSync(LOG, (r.stdout || '') + (r.stderr || ''));
  log(r.status === 0 ? `IIS: https://${host}/ → http://127.0.0.1:${port}/` : `IIS front end NOT configured (exit ${r.status}) — the dashboard works on the server; see docs/INTERNAL_TLS_SETUP.md. ${String(r.stdout || r.stderr || '').trim().split(/\r?\n/).slice(-2).join(' ')}`);
}

async function probe(port) {
  // A-03 test seam (CI rollback pass only): the variable travels from Setup's environment like SDP_SETUP_PGSUPERPASS
  if (process.env.SDP_SETUP_TEST_FAIL_PROBE === '1') { log('TEST SEAM: SDP_SETUP_TEST_FAIL_PROBE=1 — health check forced to fail'); throw new Error('forced probe failure (test seam SDP_SETUP_TEST_FAIL_PROBE=1)'); }
  const until = Date.now() + 120000; let last = '';
  while (Date.now() < until) {
    for (const p of ['/ready', '/api/auth/config']) {
      try { const r = await fetch(`http://127.0.0.1:${port}${p}`); if (r.ok) return p; last = `${p} HTTP ${r.status}`; if (r.status !== 404) break; } catch (e) { last = e.message; break; }
    }
    await new Promise((r) => setTimeout(r, 2000));
  }
  const t = serviceLogTail();
  if (t.file) log(`--- last lines of logs\\${t.file} ---\n${t.tail}\n--- end ---`);
  throw new Error(`the service did not answer on port ${port} within 2 minutes (${last})${t.cause ? ' — service error: ' + t.cause.slice(0, 300) : ''} — see logs\\${t.file || 'service-*.log'}`);
}

function swapNodeModules(staged) {
  const live = path.join(DIR, 'node_modules'), prev = path.join(DIR, '.rollback', 'node_modules.prev');
  fs.mkdirSync(path.dirname(prev), { recursive: true });
  fs.rmSync(prev, { recursive: true, force: true });
  const hadLive = fs.existsSync(live);
  if (hadLive) fs.renameSync(live, prev);
  try { fs.renameSync(staged, live); }
  catch (e) { if (hadLive) { try { fs.renameSync(prev, live); } catch (_) {} } throw e; }   // never leave the tree without node_modules
  log('dependencies: the Windows build shipped with Setup is in place (offline install)');
  return () => { try { fs.rmSync(live, { recursive: true, force: true }); if (fs.existsSync(prev)) fs.renameSync(prev, live); log('dependencies restored'); } catch (e) { log('dependencies restore failed: ' + e.message); } };
}

/** Does something answer on 127.0.0.1:port? (a TCP connect, 1 s) */
function portOpen(port) {
  return new Promise((resolve) => {
    const net = require('net');
    const s = net.createConnection({ host: '127.0.0.1', port: Number(port) });
    const done = (v) => { try { s.destroy(); } catch (_) {} resolve(v); };
    s.setTimeout(1000, () => done(false));
    s.once('connect', () => done(true));
    s.once('error', () => done(false));
  });
}
/**
 * A-03: stop the application that is running NOW (pm2 process and/or Windows service), before any file is
 * replaced. Checks BOTH hosts (a Windows service started by hand, a pm2 process left by 1.x). Returns
 * { kinds:[...] } or null when nothing ran. Waits until the port no longer answers; when it still does after
 * `waitMs`, throws (with e.stopped) — replacing files under a live process is exactly what this prevents.
 */
async function stopRunningHost({ mode, envExists, env = {}, port, run, portOpen: isOpen = portOpen, waitMs = 30000, pollMs = 1000, log: say = log } = {}) {
  if (!(mode === 'update' || mode === 'repair') || !envExists) return null;
  const S = require(path.join(ROOT, 'services', 'serviceControl'));
  const deps = run ? { run } : {};
  const kinds = [];
  const pm2 = S.status({ ...env, SDP_SERVICE: 'pm2' }, deps);
  if (pm2.state === 'running') { S.stop({ ...env, SDP_SERVICE: 'pm2' }, deps); kinds.push('pm2'); say(`stopped the running pm2 process ${pm2.name} before replacing files`); }
  const win = S.status({ SDP_SERVICE: 'windows' }, deps);
  if (win.state === 'running' || win.state === 'starting') { S.stop({ SDP_SERVICE: 'windows' }, deps); kinds.push('windows'); say(`stopped the running Windows service ${win.name} before replacing files`); }
  if (!kinds.length) { say('no running SDP Dashboard process found — nothing to stop'); return null; }
  const stopped = { kinds };
  const until = Date.now() + waitMs;
  while (await isOpen(port)) {
    if (Date.now() >= until) {
      const e = new Error(`the application still answers on port ${port} ${Math.round(waitMs / 1000)} s after it was stopped — no file was replaced`);
      e.stopped = stopped; throw e;
    }
    await new Promise((r) => setTimeout(r, pollMs));
  }
  return stopped;
}
/** Start again what stopRunningHost stopped (failure before any file change). Best effort, per host. */
function startHosts(stopped, env = {}, { run, log: say = log } = {}) {
  const S = require(path.join(ROOT, 'services', 'serviceControl'));
  for (const kind of (stopped && stopped.kinds) || []) {
    try { S.start({ ...env, SDP_SERVICE: kind }, run ? { run } : {}); say(`${kind}: the application stopped by this Setup is started again`); }
    catch (e) { say(`${kind}: restart failed — ${e.message}`); }
  }
}

/**
 * The update / repair / new flow, every step injected (tests drive it with fakes). Returns { ok, error }.
 * Order: preflight (A-01 + A-04, no change) → .env plan → STOP the running app (A-03) → dependencies →
 * package → .env/database → migrate → firewall → service → IIS → probe. A failure gives back what ran before.
 */
async function runUpdate(deps, { mode = MODE } = {}) {
  const say = deps.log || log;
  const st = { touched: false, applied: false, undoDeps: null, stopped: null, started: null };
  try {
    const plan = await deps.preflight();
    if (deps.preflightOnly) { say('preflight OK'); return { ok: true }; }
    st.touched = true;
    await deps.writeEnvPlan(plan);
    st.stopped = await deps.stopCurrentHost();
    st.undoDeps = (await deps.swapDeps()) || null;
    st.applied = !!(await deps.applyPackage());
    const env = await deps.envSteps(plan);
    await deps.migrate(env);
    await deps.firewall(env);
    st.started = deps.serviceKind(env);
    await deps.registerService(st.started, env);
    await deps.iis(env);
    const via = await deps.probe(env);
    await deps.writeResult({ ok: true, via, env, stopped: st.stopped });
    return { ok: true };
  } catch (e) {
    say('FAILED: ' + e.message);
    if (!st.stopped && e && e.stopped) st.stopped = e.stopped;
    if (!st.touched) {
      say('nothing was changed');
      await deps.writeResult({ ok: false, error: e.message, stopped: null });
      return { ok: false, error: e.message };
    }
    // the new version may be running (or half-started): stop it before its files are taken away
    if (st.started && mode !== 'new') { try { await deps.stopHost(st.started); } catch (e5) { say('stop before rollback: ' + e5.message); } }
    if (st.applied && mode !== 'new') {
      say('rolling back the application files…');
      try { await deps.rollbackFiles(); } catch (e2) { say('rollback failed: ' + e2.message); }
    }
    if (st.undoDeps) st.undoDeps();
    if (mode !== 'new') {
      try {
        const prevEnv = (await deps.restoreEnv()) || {};
        if (st.applied || st.started || !st.stopped) {
          const kindNow = deps.previousServiceKind(prevEnv);   // decided on the files that are back, not on what Setup wrote
          await deps.fixHostForRollback(kindNow, prevEnv);
          await deps.registerService(kindNow, { ...prevEnv, SDP_SERVICE: kindNow });
          say(`previous version restarted (${kindNow})`);
        } else {
          // nothing was replaced: start exactly what this Setup stopped
          await deps.startHosts(st.stopped, prevEnv);
        }
      } catch (e3) { say('restart after rollback failed: ' + e3.message); }
    }
    await deps.writeResult({ ok: false, error: e.message, stopped: st.stopped });
    return { ok: false, error: e.message };
  }
}

async function main() {
  log(`post-install ${MODE} dir=${DIR} port=${PORT} node=${process.version}`);
  const envFile = path.join(DIR, '.env');
  if (MODE === 'uninstall') {
    const env = readEnv(envFile);
    unregisterService(env);
    firewall(env.PORT || PORT, { remove: true });
    log('service removed. Data, backups and .env are removed only when "also remove data" was chosen.');
    return;
  }
  const mgr = path.join(ROOT, 'tools', 'sdp-manager.js');
  const nodePath = [path.join(DIR, 'node_modules'), process.env.NODE_PATH].filter(Boolean).join(path.delimiter);
  const pkgZip = arg('--package', null);
  // what was running BEFORE this Setup — a rollback must give back exactly that, not the new host
  const envBefore = fs.existsSync(envFile) ? fs.readFileSync(envFile) : null;
  const staged = arg('--node-modules', null);
  const d = envDefaults(); const { _appPass, ...wanted } = d;
  const freshEnv = MODE === 'new' && !fs.existsSync(envFile);
  const writeResult = (r) => {
    const out = r.ok
      ? { ok: true, mode: MODE, at: new Date().toISOString(), url: `http://localhost:${(r.env && r.env.PORT) || PORT}/`, log: LOG, stopped: r.stopped || null }
      : { ok: false, mode: MODE, at: new Date().toISOString(), error: String(r.error || '').slice(0, 500), log: LOG, stopped: r.stopped || null };
    if (r.ok) { log(`OK — SDP Dashboard answers on http://localhost:${(r.env && r.env.PORT) || PORT} (${r.via})`); try { fs.rmSync(path.join(DIR, '.rollback', 'node_modules.prev'), { recursive: true, force: true }); } catch (_) {} }
    try { fs.writeFileSync(path.join(DIR, 'logs', 'setup-last.json'), JSON.stringify(out, null, 2)); } catch (_) {}
  };
  const S = () => require(path.join(ROOT, 'services', 'serviceControl'));
  const r = await runUpdate({
    log,
    preflightOnly: has('--preflight-only'),
    async preflight() {
      preflight(envFile);
      if (has('--preflight-only')) return null;
      // A-04: every .env and secrets check BEFORE the first change (a refusal costs nothing and changes nothing)
      return freshEnv ? null : planEnv(envFile, {
        wanted: { NODE_ENV: 'production', PORT, BIND_HOST: '127.0.0.1', SDP_BACKUP_DIR: wanted.SDP_BACKUP_DIR, DASHBOARD_API_KEY: wanted.DASHBOARD_API_KEY, SDP_SERVICE: serviceKind(readEnv(envFile)) },
        pgDir: staged && fs.existsSync(path.join(staged, 'pg')) ? staged : undefined,
      });
    },
    // the repaired .env BEFORE step 2: the sdp-manager backup reads SDP_BACKUP_KEY from it and encrypts
    // (a later failure restores envBefore)
    writeEnvPlan(plan) { if (plan) writePlannedEnv(envFile, plan, log); },
    // A-03: the 1.x pm2 process (or a hand-started service) must not run while files are replaced
    stopCurrentHost: () => stopRunningHost({ mode: MODE, envExists: fs.existsSync(envFile), env: readEnv(envFile), port: readEnv(envFile).PORT || PORT }),
    swapDeps() {
      // 1 dependencies
      if (staged && fs.existsSync(staged)) return swapNodeModules(staged);
      if (!fs.existsSync(path.join(DIR, 'node_modules', 'express'))) log('no dependencies shipped with this Setup — `npm ci` after the copy (needs the internet)');
      return null;
    },
    applyPackage() {
      // 2 the package
      if (!pkgZip) return false;
      const update = MODE === 'update' && fs.existsSync(envFile);
      sh(process.execPath, [mgr, 'update', pkgZip, '--dir', DIR, ...(update ? [] : ['--no-backup']), '--no-npm', '--no-migrate', '--no-restart',
        // an update to the version already installed re-applies it (backup first) — a downgrade stays refused
        ...(MODE === 'repair' || MODE === 'update' ? ['--reinstall'] : []), ...(has('--allow-unsigned') ? ['--allow-unsigned'] : [])], { env: { NODE_PATH: nodePath }, shell: false });
      return true;
    },
    async envSteps() {
      if (!fs.existsSync(path.join(DIR, 'node_modules', 'express'))) sh('npm', ['ci', '--omit=dev', '--no-audit', '--no-fund']);
      // 3 + 4 .env and database (update/repair: already written before step 1)
      if (freshEnv) {
        const appPass = await createDatabase(d);
        if (appPass !== d._appPass) wanted.PG_URL = wanted.PG_URL.replace(encodeURIComponent(d._appPass), encodeURIComponent(appPass));
        writeEnv(envFile, { ...wanted, SDP_SERVICE: serviceKind({}) });
        log('.env created — bootstrap admin "admin", its password is DASH_PASS in .env: change it at first sign-in');
      }
      const env = readEnv(envFile);
      const bad = envProblems(env);
      if (bad.length) throw new Error(`.env would be refused by this version: ${bad.join('; ')} — fix ${envFile} and run Setup again`);
      return env;
    },
    // 5 schema
    migrate(env) { sh(process.execPath, [path.join(DIR, 'db', 'migrate.js')], { env, shell: false }); },
    // 6 firewall, 7 service, 8 IIS, 9 probe
    firewall(env) { firewall(env.PORT || PORT); },
    serviceKind,
    registerService(kind, env) { registerService(kind, env); },
    iis(env) { iisFrontEnd(env.PORT || PORT); },
    probe(env) { return probe(env.PORT || PORT); },
    stopHost(kind) { try { S().stop({ ...readEnv(envFile), SDP_SERVICE: kind }); log(`${kind}: the new version stopped before the rollback`); } catch (e) { log(`${kind}: stop before rollback — ${e.message}`); } },
    startHosts: (stopped, env) => startHosts(stopped, env),
    rollbackFiles() { sh(process.execPath, [mgr, 'rollback', '--dir', DIR, '--no-restart'], { env: { NODE_PATH: nodePath }, shell: false }); },
    restoreEnv() {
      if (envBefore) { fs.writeFileSync(envFile, envBefore); log('.env restored to its state before this Setup'); }
      return readEnv(envFile);
    },
    previousServiceKind: (prevEnv) => previousServiceKind(prevEnv, DIR),
    fixHostForRollback(kindNow, prevEnv) {
      if (kindNow === 'pm2' && prevEnv.SDP_SERVICE === 'windows') { setEnvValue(envFile, 'SDP_SERVICE', 'pm2'); log('.env: SDP_SERVICE set back to pm2 — the previous version cannot run on the bundled Node.js'); }
      // an older installation ran under pm2 with the system Node.js: starting it with the Windows service
      // (and the Node.js shipped with this Setup) fails on native modules built for another Node version
      if (kindNow === 'pm2' && fs.existsSync(SVC_EXE())) { try { sh(SVC_EXE(), ['uninstall'], { shell: false }); log('Windows service removed — the previous version runs under pm2'); } catch (e4) { log('service removal: ' + e4.message); } }
    },
    writeResult,
  }, { mode: MODE });
  if (!r.ok) process.exit(1);
}

