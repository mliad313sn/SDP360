'use strict';
// Everything Setup.exe does to the machine after copying its payload (installer v2.1, 2026-10-29).
// Called by SDP-Dashboard.iss through Exec (exit code checked: a failure stops the wizard and shows the
// log) and runnable by hand for a scripted install:
//
//   node post-install.js --dir C:\Apps\SDP-Dashboard --package sdp-dashboard-2.0.0.zip --mode new|update|repair|uninstall
//        [--port 3456] [--pg-host localhost --pg-port 5432 --db-name sdp_dashboard --db-user sdp_app]
//        [--service auto|windows|pm2] [--service-account DOMAIN\user] [--node-modules <staged dir>]
//        [--public-host itops.example.com --cert-thumbprint <sha1>] [--allow-unsigned] [--remove-data]
//        [--preflight-only] [--ignore-legacy-store]   (A-01: refuse a 1.x install whose data is still in SQLite)
//
// Secrets arrive in the ENVIRONMENT only (SDP_SETUP_PGSUPERPASS, SDP_SETUP_SVCPASS) and are never logged
// or put on a command line. Steps, each logged to <dir>\logs\setup-<stamp>.log:
//   0 update/repair (A-03): the application running NOW (pm2 process of a 1.x server, or a Windows service
//     started by hand) is stopped and the port released BEFORE any file is replaced; a failure before any
//     file change starts exactly that host again. Test seam: SDP_SETUP_TEST_FAIL_PROBE=1 fails step 9.
//   1 dependencies: the node_modules folder built by CI for Windows (offline install), swapped in with the
//     previous one kept for the rollback; `npm ci` only when Setup carries none
//   2 the package through tools/sdp-manager.js — signature + hashes, database backup first on an update,
//     rollback point (the whole tree when the installation has no manifest), copy
//   3 .env: created on `new` (generated keys, bootstrap admin, PG_URL); kept otherwise, missing keys appended
//     (DASHBOARD_API_KEY above all — production refuses to start without it)
//   4 PostgreSQL role + database on `new`, through the `pg` driver (no psql on PATH needed)
//   5 db/migrate.js
//   6 Windows Firewall: the application port from 127.0.0.1 only
//   7 the service: the native Windows service SDPDashboard (new installs) or pm2 (servers already on pm2),
//     restarted stop → wait → start
//   8 IIS front end when a public host name is given and IIS has URL Rewrite + ARR (best effort)
//   9 health probe on /ready; any failure after step 2 rolls everything back and exits 1
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..');        // the bootstrap copy (Setup) or the install folder
function arg(flag, def) { const i = process.argv.indexOf(flag); return i > 0 && process.argv[i + 1] != null && !process.argv[i + 1].startsWith('--') ? process.argv[i + 1] : def; }
const has = (flag) => process.argv.includes(flag);
const DIR = path.resolve(arg('--dir', process.cwd()));
const MODE = arg('--mode', 'new');
const PORT = arg('--port', '3456');
const stamp = new Date().toISOString().replace(/[:.]/g, '-');
fs.mkdirSync(path.join(DIR, 'logs'), { recursive: true });
const LOG = path.join(DIR, 'logs', `setup-${stamp}.log`);
const SECRET_RE = /((?:PG)?PASS(?:WORD)?|SECRET|KEY|TOKEN)=\S+/gi;
function log(m) { const line = `[${new Date().toISOString()}] ${String(m).replace(SECRET_RE, '$1=***')}`; try { fs.appendFileSync(LOG, line + '\n'); } catch (_) {} process.stdout.write(line + '\n'); }
function sh(cmd, args, opts = {}) {
  log(`$ ${path.basename(cmd)} ${args.filter((a) => !/pass|secret/i.test(a)).join(' ')}`);
  const r = spawnSync(cmd, args, { encoding: 'utf8', cwd: DIR, shell: opts.shell != null ? opts.shell : process.platform === 'win32' && !/\.exe$/i.test(cmd), maxBuffer: 64 * 1024 * 1024, ...opts, env: { ...process.env, ...(opts.env || {}) } });
  if (r.stdout) fs.appendFileSync(LOG, r.stdout);
  if (r.stderr) fs.appendFileSync(LOG, r.stderr);
  if (r.status !== 0) throw new Error(`${path.basename(cmd)} exited ${r.status}: ${String(r.stderr || r.stdout || (r.error && r.error.message) || '').trim().slice(-500)}`);
  return r;
}

/** The .env parser on a string (pure). */
function readEnvText(text) {
  const out = {};
  for (const l of String(text == null ? '' : text).split(/\r?\n/)) { const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(l); if (m) out[m[1]] = m[2].replace(/^"(.*)"$/, '$1'); }
  return out;
}
function readEnv(file) {
  try { return readEnvText(fs.readFileSync(file, 'utf8')); } catch (_) { return {}; }
}
const envLines = (text) => (text == null ? ['# SDP Dashboard — generated by Setup ' + stamp, '# Keep a copy of SDP_CONFIG_KEY and SDP_BACKUP_KEY somewhere safe off this server: a backup restored elsewhere needs them.'] : String(text).replace(/\r?\n$/, '').split(/\r?\n/));
const joinEnv = (lines) => lines.join('\r\n') + '\r\n';
/** Pure: append the keys that are missing (`text` null = no .env yet) — an existing value is never changed. */
function writeEnvText(text, wanted) {
  const have = readEnvText(text); const lines = envLines(text); const added = [];
  for (const [k, v] of Object.entries(wanted)) if (!(k in have) && v != null) { lines.push(`${k}=${v}`); added.push(k); }
  return { text: joinEnv(lines), added };
}
/** Append the keys that are missing — an existing value is never changed. */
function writeEnv(file, wanted) {
  const r = writeEnvText(fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null, wanted);
  fs.writeFileSync(file, r.text);
  return r.added;
}
/** Pure: replace one key's value in place (the line is rewritten, everything else is kept). */
function setEnvValueText(text, key, value) {
  const re = new RegExp('^\\s*' + key + '\\s*=');
  let done = false;
  const out = envLines(text).map((l) => { if (!done && re.test(l)) { done = true; return `${key}=${value}`; } return l; });
  if (!done) out.push(`${key}=${value}`);
  return joinEnv(out);
}
function setEnvValue(file, key, value) { fs.writeFileSync(file, setEnvValueText(fs.readFileSync(file, 'utf8'), key, value)); }
/** The API-key minimum of the version that will run: the Setup bootstrap first, then the install folder, else 32. */
function apiKeyMin() {
  for (const base of [ROOT, DIR]) { try { return require(path.join(base, 'services', 'apiKey')).MIN_LENGTH || 32; } catch (_) {} }
  return 32;
}
const defaultRand = (n, enc) => crypto.randomBytes(n).toString(enc);
/**
 * Values an older .env can carry that this version refuses to start with — pure core (A-04): returns the repaired
 * text, the keys fixed, the log lines (key NAMES only, never a value) and whether a copy of the previous .env must
 * be kept. Today: DASHBOARD_API_KEY shorter than the minimum (services/apiKey.js refuses it in production), a
 * missing SDP_CONFIG_KEY, a missing SDP_BACKUP_KEY.
 */
function repairEnvText(text, { minApiKey = 32, rand = defaultRand, copyName = `.env.before-setup-${stamp}` } = {}) {
  const have = readEnvText(text); const fixed = [], messages = []; let out = text, copy = false;
  if (have.DASHBOARD_API_KEY != null && have.DASHBOARD_API_KEY.length < minApiKey) {
    copy = true;
    out = setEnvValueText(out, 'DASHBOARD_API_KEY', rand(32, 'hex'));
    fixed.push('DASHBOARD_API_KEY');
    messages.push(`.env: DASHBOARD_API_KEY was ${have.DASHBOARD_API_KEY.length} characters (minimum ${minApiKey}) — replaced with a new random key; previous .env kept as ${copyName}. Any external tool that used the old key must be given the new one.`);
  }
  // 2.0 refuses to start in production without SDP_CONFIG_KEY (services/configSecrets.js). A 1.x .env has none, so its
  // stored secrets are plaintext: a new key keeps them readable (they encrypt on their next save). Never replaced when
  // present — a key that is already there may be the one existing secrets are encrypted with.
  if (!have.SDP_CONFIG_KEY) {
    copy = true;
    out = setEnvValueText(out, 'SDP_CONFIG_KEY', rand(32, 'base64url'));
    fixed.push('SDP_CONFIG_KEY');
    messages.push('.env: SDP_CONFIG_KEY was missing (required by this version in production) — generated. Keep a copy of .env off this server: a database restored elsewhere needs the same key.');
  } else if (have.SDP_CONFIG_KEY.length < 16) {
    messages.push('.env: SDP_CONFIG_KEY is shorter than 16 characters — this version will refuse to start. Not changed automatically (existing secrets may be encrypted with it).');
  }
  if (!have.SDP_BACKUP_KEY) {
    out = setEnvValueText(out, 'SDP_BACKUP_KEY', rand(32, 'base64url'));
    fixed.push('SDP_BACKUP_KEY');
    messages.push('.env: SDP_BACKUP_KEY was missing — generated (backups are now encrypted; keep a copy of .env off this server).');
  }
  return { text: out, fixed, messages, copy };
}
/** Thin wrapper on repairEnvText for a file: the previous .env is kept, the log names the key (never its value). */
function repairEnv(file, log) {
  const copyPath = `${file}.before-setup-${stamp}`;
  const r = repairEnvText(fs.readFileSync(file, 'utf8'), { minApiKey: apiKeyMin(), copyName: path.basename(copyPath) });
  if (r.copy && !fs.existsSync(copyPath)) fs.copyFileSync(file, copyPath);
  if (r.fixed.length) fs.writeFileSync(file, r.text);
  for (const m of r.messages) log(m);
  return r.fixed;
}
/** What this version refuses at startup in production (server.js, services/apiKey.js, backendGuard, configSecrets) — checked BEFORE starting it, so a failure names the cause instead of a 2-minute timeout. */
function envProblems(env) {
  const p = [];
  if (!env.DASH_USER) p.push('DASH_USER is missing');
  if (!env.DASH_PASS) p.push('DASH_PASS is missing'); else if (env.DASH_PASS.length < 12) p.push('DASH_PASS is shorter than 12 characters');
  if (!(env.PG_URL || env.DATABASE_URL)) p.push('PG_URL is missing (PostgreSQL is the only database)');
  if (!env.DASHBOARD_API_KEY || env.DASHBOARD_API_KEY.length < 32) p.push('DASHBOARD_API_KEY is missing or shorter than 32 characters');
  if (env.NODE_ENV === 'production' && (env.SDP_CONFIG_KEY || '').length < 16 && env.SDP_ALLOW_PLAINTEXT_SECRETS !== '1') p.push('SDP_CONFIG_KEY is missing or shorter than 16 characters');
  return p;
}
/**
 * Secrets-key continuity (pure): `rows` = report_config {key,value}. A database that already holds `enc:` secrets
 * must keep the key it was encrypted with — a NEW key reads them as empty (services/configSecrets.js), silently
 * breaking SMTP / Meraki / SSO. Returns the keys of encrypted values and those this key cannot open.
 */
function checkSecretRows(rows, passphrase) {
  let cs = null;   // the bootstrap copy carries it (build.ps1 step 6); the install folder as fallback
  for (const base of [ROOT, DIR]) { try { cs = require(path.join(base, 'services', 'configSecrets')); break; } catch (_) {} }
  if (!cs) throw new Error('services/configSecrets.js not found in the Setup bootstrap or the install folder');
  const key = passphrase ? cs.keyFrom(passphrase) : null;
  const encrypted = rows.filter((r) => cs.isEncrypted(r.value)).map((r) => r.key);
  const unreadable = encrypted.filter((k) => { const v = rows.find((r) => r.key === k).value; const d = key ? cs.decryptValue(v, key) : null; return d == null || d === ''; });
  return { encrypted, unreadable };
}
/** The pg driver of the version that will run: the staged --node-modules folder when Setup carries one, else the install folder's. */
function stagedPgDir() {
  const staged = arg('--node-modules', null);
  return staged && fs.existsSync(path.join(staged, 'pg')) ? staged : path.join(DIR, 'node_modules');
}
async function secretsKeyGuard(env, { connect, pgDir } = {}) {
  let rows;
  try {
    const dir = pgDir || stagedPgDir();
    const open = connect || (async (url) => { const { Client } = require(path.join(dir, 'pg')); const c = new Client({ connectionString: url }); await c.connect(); return c; });
    const c = await open(env.PG_URL || env.DATABASE_URL, { pgDir: dir });
    try { rows = (await c.query('SELECT key, value FROM report_config')).rows; } finally { await c.end(); }
  } catch (e) { log(`secrets check skipped (database not readable: ${e.message})`); return; }
  const { encrypted, unreadable } = checkSecretRows(rows, env.SDP_CONFIG_KEY);
  if (!encrypted.length) return;
  if (!env.SDP_CONFIG_KEY) throw new Error(`the database holds ${encrypted.length} encrypted secret(s) (${encrypted.join(', ')}) but .env has no SDP_CONFIG_KEY — a new key would read them as EMPTY. Put the original SDP_CONFIG_KEY back into .env (look in older .env copies, or \`pm2 env <id>\` on the old process) and run Setup again. Nothing was changed.`);
  if (unreadable.length === encrypted.length) throw new Error(`SDP_CONFIG_KEY in .env cannot decrypt the stored secrets (${unreadable.join(', ')}) — it is not the key they were encrypted with. Restore the original key and run Setup again. Nothing was changed.`);
  if (unreadable.length) log(`warning: ${unreadable.length} stored secret(s) cannot be read with this key (${unreadable.join(', ')}) — re-enter them in Admin after the update`);
}
/**
 * Pure (A-04): the complete .env this run will write — the missing keys appended (writeEnvText), then the repairs
 * (repairEnvText) — and what this version would refuse at startup, computed in memory without touching disk.
 */
function envPreflight(currentText, { wanted = {}, minApiKey = 32, rand, copyName } = {}) {
  const w = writeEnvText(currentText, wanted);
  const r = repairEnvText(w.text, { minApiKey, rand, copyName });
  return { text: r.text, added: w.added, fixed: r.fixed, messages: r.messages, copy: r.copy, problems: envProblems(readEnvText(r.text)) };
}
/**
 * Every .env and secrets check of an update/repair, BEFORE the first change (A-04). The secrets guard runs on the
 * ORIGINAL .env — a missing SDP_CONFIG_KEY with encrypted rows refuses before a key is generated (B1, 44ad8d3).
 * Throws on a refusal; writes nothing.
 */
async function planEnv(envFile, { wanted, minApiKey = apiKeyMin(), connect, pgDir } = {}) {
  const original = fs.existsSync(envFile) ? fs.readFileSync(envFile, 'utf8') : null;
  await secretsKeyGuard(readEnvText(original), { connect, pgDir });
  const pre = envPreflight(original, { wanted, minApiKey, copyName: path.basename(envFile) + '.before-setup-' + stamp });
  if (pre.problems.length) throw new Error(`.env would be refused by this version: ${pre.problems.join('; ')} — fix ${envFile} and run Setup again. Nothing was changed.`);
  return { ...pre, original };
}
/** Write the planned .env (before step 2, so the sdp-manager backup reads SDP_BACKUP_KEY); the previous one is kept when a key was replaced or generated. */
function writePlannedEnv(envFile, plan, logFn = log) {
  const copyPath = `${envFile}.before-setup-${stamp}`;
  if (plan.copy && plan.original != null && !fs.existsSync(copyPath)) fs.writeFileSync(copyPath, plan.original);
  if (plan.text !== plan.original) fs.writeFileSync(envFile, plan.text);
  logFn(`.env kept${plan.added.length ? ' — added ' + plan.added.join(', ') : ''}`);
  for (const m of plan.messages) logFn(m);
}
