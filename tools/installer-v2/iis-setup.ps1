<#
  SDP Dashboard — IIS front end (called by post-install.js when the wizard gets a public host name).
  Best effort and idempotent: it never stops the installation. Exit codes:
    0  configured     2  prerequisites missing (IIS / URL Rewrite / ARR) — nothing changed     1  error

  What it does (same design as iis/web.config and docs/INTERNAL_TLS_SETUP.md):
    - ARR proxy on, 5-minute proxy timeout (long PPTX renders), X-Forwarded-* server variables allowed
    - a site "SDP Dashboard" whose root holds a generated web.config: reverse proxy to http://127.0.0.1:<port>,
      150 MB request limit (inspection photos)
    - binding https://<host>:443 with the certificate <thumbprint> from LocalMachine\My (SNI);
      without a thumbprint, http://<host>:80 only (a warning says so)
#>
param(
  [Parameter(Mandatory = $true)][string]$HostName,
  [Parameter(Mandatory = $true)][int]$Port,
  [Parameter(Mandatory = $true)][string]$AppDir,
  [string]$Thumbprint = ''
)
$ErrorActionPreference = 'Stop'
function Say($m) { Write-Output ("[iis] " + $m) }

if (-not (Get-Service W3SVC -ErrorAction SilentlyContinue)) { Say 'IIS (W3SVC) is not installed'; exit 2 }
try { Import-Module WebAdministration -ErrorAction Stop } catch { Say 'WebAdministration module unavailable'; exit 2 }
if (-not (Test-Path 'HKLM:\SOFTWARE\Microsoft\IIS Extensions\URL Rewrite')) { Say 'URL Rewrite module is not installed'; exit 2 }
$proxy = Get-WebConfiguration -PSPath 'MACHINE/WEBROOT/APPHOST' -Filter 'system.webServer/proxy' -ErrorAction SilentlyContinue
if (-not $proxy) { Say 'Application Request Routing (ARR) is not installed'; exit 2 }

try {
  Set-WebConfigurationProperty -PSPath 'MACHINE/WEBROOT/APPHOST' -Filter 'system.webServer/proxy' -Name 'enabled' -Value 'True'
  Set-WebConfigurationProperty -PSPath 'MACHINE/WEBROOT/APPHOST' -Filter 'system.webServer/proxy' -Name 'timeout' -Value '00:05:00'
  foreach ($v in 'HTTP_X_FORWARDED_PROTO', 'HTTP_X_FORWARDED_HOST', 'HTTP_X_FORWARDED_FOR') {
    $have = Get-WebConfiguration -PSPath 'MACHINE/WEBROOT/APPHOST' -Filter "system.webServer/rewrite/allowedServerVariables/add[@name='$v']"
    if (-not $have) { Add-WebConfiguration -PSPath 'MACHINE/WEBROOT/APPHOST' -Filter 'system.webServer/rewrite/allowedServerVariables' -Value @{ name = $v } }
  }
  $root = Join-Path $AppDir 'iis-site'
  New-Item -ItemType Directory -Force -Path $root | Out-Null
  $proto = if ($Thumbprint) { 'https' } else { 'http' }
  $cfg = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by SDP Dashboard Setup (tools/installer-v2/iis-setup.ps1). Re-run Setup (Repair) to regenerate. -->
<configuration>
  <system.webServer>
    <rewrite>
      <rules>
        <rule name="ReverseProxyToNode" stopProcessing="true">
          <match url="(.*)" />
          <action type="Rewrite" url="http://127.0.0.1:$Port/{R:1}" />
          <serverVariables>
            <set name="HTTP_X_FORWARDED_PROTO" value="$proto" />
            <set name="HTTP_X_FORWARDED_HOST" value="{HTTP_HOST}" />
            <set name="HTTP_X_FORWARDED_FOR" value="{REMOTE_ADDR}" />
          </serverVariables>
        </rule>
      </rules>
    </rewrite>
    <security>
      <requestFiltering>
        <requestLimits maxAllowedContentLength="157286400" />
      </requestFiltering>
    </security>
    <httpErrors existingResponse="PassThrough" />
  </system.webServer>
</configuration>
"@
  Set-Content -Path (Join-Path $root 'web.config') -Value $cfg -Encoding UTF8

  $site = Get-Website -Name 'SDP Dashboard' -ErrorAction SilentlyContinue
  if (-not $site) {
    if ($Thumbprint) { New-Website -Name 'SDP Dashboard' -PhysicalPath $root -HostHeader $HostName -Port 443 -Ssl -SslFlags 1 | Out-Null }
    else { New-Website -Name 'SDP Dashboard' -PhysicalPath $root -HostHeader $HostName -Port 80 | Out-Null }
    Say "site created for $HostName"
  } else {
    Set-ItemProperty "IIS:\Sites\SDP Dashboard" -Name physicalPath -Value $root
    Say 'site already there — web.config regenerated'
  }
  if ($Thumbprint) {
    $cert = Get-ChildItem "Cert:\LocalMachine\My\$Thumbprint" -ErrorAction SilentlyContinue
    if (-not $cert) { Say "certificate $Thumbprint not found in LocalMachine\My — HTTPS binding left without a certificate"; exit 1 }
    $b = Get-WebBinding -Name 'SDP Dashboard' -Protocol https -HostHeader $HostName -ErrorAction SilentlyContinue
    if (-not $b) { New-WebBinding -Name 'SDP Dashboard' -Protocol https -Port 443 -HostHeader $HostName -SslFlags 1; $b = Get-WebBinding -Name 'SDP Dashboard' -Protocol https -HostHeader $HostName }
    $b.AddSslCertificate($Thumbprint, 'My')
    Say "https://$HostName/ bound to certificate $($cert.Subject)"
  } else {
    Say "WARNING: no certificate thumbprint — http://$HostName/ only. Bind a certificate before opening the site to users."
  }
  Start-Website -Name 'SDP Dashboard' -ErrorAction SilentlyContinue
  exit 0
} catch {
  Say ("error: " + $_.Exception.Message)
  exit 1
}
