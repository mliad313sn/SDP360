#!/usr/bin/env node
'use strict';
// F-DATA-12 (C06, C19, N12) — widget catalogue with a decision column. For every widget of the shipped dashboard
// definitions (services/dashboardSeeds.js, plus the draft decision-kpis definition) it lists: the metric, the
// persona (dashboard audience, or the widget's own audience_role), the sync job behind the metric's module and
// its freshness limit, the metric's owner role, where the colour threshold comes from, the action link, the
// data states the viewer shows for that kind of widget, and the decision the widget supports.
// Generated, never hand-edited:
//
//   node tools/agent/widget-catalogue.js           writes docs/ops/WIDGET-CATALOGUE.md
//   node tools/agent/widget-catalogue.js --check   exits 1 when the committed file is out of date
//
// It invents nothing: a decision, owner or audience role nobody wrote reads "not stated" / "to be named".
// Filling them is a human act (KPI committee / product owner), done in the definition, not here.

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'docs', 'ops', 'WIDGET-CATALOGUE.md');

const read = (p) => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n');

// Data states the viewer (public/dashboards.html + public/lib/dashboardRender.js) shows, by render family.
// "page" = handled once for the whole dashboard (status line), not per widget.
// Loading and denied/unavailable are page-level for every widget: status('Loading…') / 'Data unavailable: …'.
const PAGE_STATES = 'loading (page) · denied/unavailable (page)';
const STATES = {
  tile: 'empty ("—") · stale (badge, colour withheld) · partial (period / source read in part)',
  line: 'empty (gap) · stale (badge) · partial (last point *)',
  'bar-list': 'empty (not measured row) · stale (colour withheld) · partial (note)',
  'sortable-table': 'empty (not measured row) · stale (colour withheld) · partial (note)',
  'rag-grid': 'empty (not measured cell) · stale (colour withheld) · partial (note)',
  'small-multiples': 'empty (not measured panel) · partial (*)',
  'tracker-rag': 'no metric — tracker data',
  'action-table': 'no metric — action list',
  markdown: 'static text',
};

const LEGACY_PAGES = [
  ['kpi-dictionary.html', '1.11 KPI dictionary page'],
  ['publication.html', '1.11 publication page'],
];

function threshold(w, m) {
  if (w.rag && typeof w.rag === 'string') return 'policy `' + w.rag + '` (widget)';
  if (w.rag && typeof w.rag === 'object') return 'inline on the widget';
  if (m && m.rag_policy) return 'policy `' + m.rag_policy + '` (metric)';
  return 'none';
}

function build({ root = ROOT } = {}) {
  const { SEED } = require(path.join(root, 'services', 'metricRegistry'));
  const { SEED_DASHBOARDS, DECISION_KPIS } = require(path.join(root, 'services', 'dashboardSeeds'));
  const { SOURCES } = require(path.join(root, 'services', 'publishGate'));
  const { WIDGET_TYPES } = require(path.join(root, 'services', 'dashboardWidgets'));
  const byKey = new Map(SEED.map((m) => [m.key, m]));
  const dashboards = SEED_DASHBOARDS.map((d) => ({ d, draft: false }));
  if (DECISION_KPIS) dashboards.push({ d: DECISION_KPIS, draft: true });

  const rows = [];
  for (const { d, draft } of dashboards) {
    for (const w of d.widgets || []) {
      const T = WIDGET_TYPES[w.type] || {};
      const keys = w.metric ? [w.metric] : (Array.isArray(w.metrics) ? w.metrics : []);
      const ms = keys.map((k) => byKey.get(k)).filter(Boolean);
      const m = ms[0] || null;
      const jobs = [...new Set(ms.flatMap((x) => (SOURCES[x.module] || []).map(([j, h]) => j + ' (≤ ' + h + ' h)')))];
      rows.push({
        dashboard: d.key, draft, widget: w.id, type: w.type, metric: keys.join(', '),
        persona: w.audience_role || d.audience || 'not stated',
        source: !keys.length ? '—' : jobs.length ? jobs.join('<br>') : 'typed in the app (no sync job)',
        owner: !keys.length ? '—' : (m && m.owner_role) || 'to be named',
        threshold: keys.length ? threshold(w, m) : '—',
        action: w.action_href || '—',
        states: (STATES[T.render] || 'unknown render') + ' · ' + PAGE_STATES,
        question: w.question || 'not stated',
        decision: w.decision || 'not stated',
      });
    }
  }

  const c = (v) => '`' + v + '`';
  const cell = (v) => String(v).replace(/\|/g, '\\|');
  const L = [];
  L.push('# Widget catalogue — what each shipped widget shows and which decision it supports');
  L.push('');
  L.push('Generated by `node tools/agent/widget-catalogue.js` from the code (`--check` fails when this file is stale). Do not edit by hand.');
  L.push('');
  L.push('The **Question**, **Decision** and persona columns come from optional widget fields (`question`, `decision`,');
  L.push('`audience_role`). None is filled in by the agent: "not stated" means nobody has written it yet. Writing them is a');
  L.push('KPI-committee / product-owner decision, made in the dashboard definition. Owner = the metric\'s `owner_role`');
  L.push('("to be named" until decided). Threshold source: a RAG policy named on the widget or on the metric; per-site');
  L.push('targets (`kpi_targets`, governance values) can add a target line at run time and are not listed here.');
  L.push('');
  L.push(`Widgets: **${rows.length}** · with a decision stated: **${rows.filter((r) => r.decision !== 'not stated').length}** · with an action link: **${rows.filter((r) => r.action !== '—').length}**`);
  L.push('');
  L.push('| Dashboard | Widget | Type | Metric | Persona | Source job (freshness limit) | Owner role | Threshold source | Action link | States covered | Question | Decision |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    L.push(`| ${c(r.dashboard)}${r.draft ? ' (draft, switch off)' : ''} | ${c(r.widget)} | ${r.type} | ${r.metric ? c(r.metric) : '—'} | ${cell(r.persona)} | ${r.source} | ${cell(r.owner)} | ${r.threshold} | ${r.action === '—' ? '—' : c(r.action)} | ${r.states} | ${cell(r.question)} | ${cell(r.decision)} |`);
  }
  L.push('');
  L.push('## Legacy pages (1.11 line)');
  L.push('');
  L.push('Not present at head and no redirect is served: a bookmark returns 404. Retire or redirect — **decision pending** (product owner).');
  L.push('');
  L.push('| Page | What it was | At head | Decision |');
  L.push('|---|---|---|---|');
  for (const [f, what] of LEGACY_PAGES) {
    const here = fs.existsSync(path.join(root, 'public', f));
    L.push(`| ${c(f)} | ${what} | ${here ? 'present' : 'absent'} | retire or redirect — decision pending |`);
  }
  L.push('');
  return { markdown: L.join('\n'), rows };
}

function main(argv = process.argv.slice(2), { root = ROOT, out = OUT } = {}) {
  const md = build({ root }).markdown;
  if (argv.includes('--check')) {
    const cur = fs.existsSync(out) ? read(out) : '';
    if (cur !== md) { console.error('WIDGET-CATALOGUE.md is out of date — run: node tools/agent/widget-catalogue.js'); return 1; }
    console.log('widget catalogue up to date'); return 0;
  }
  fs.writeFileSync(out, md);
  console.log('wrote ' + path.relative(ROOT, out));
  return 0;
}

if (require.main === module) process.exit(main());
module.exports = { build, main, OUT, STATES, PAGE_STATES };
