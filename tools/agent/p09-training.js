'use strict';
// P09 step 7 — one training sheet per workspace profile, French then English, built from the help content already in
// the app (public/help.html sections) and the per-profile task list (tests/e2e/fixtures/profile-tasks.js — the same
// list the browser journeys prove reachable). Writes docs/ops/pilot/training/<profile>.md. `--check` fails if stale.
// The sheets point at the help sections; they do not restate them, so the help stays the single source.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const { PROFILE_TASKS } = require(path.join(ROOT, 'tests/e2e/fixtures/profile-tasks.js'));
const WP = require(path.join(ROOT, 'public/lib/workspaceProfiles.js'));
const help = fs.readFileSync(path.join(ROOT, 'public/help.html'), 'utf8');

const strip = (s) => s.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&#39;|&rsquo;/g, '’').trim();
// 2026-11-21: the manual is one bilingual document with stable anchors; a chapter title is the <h2> span of each language.
function titles(lang) {
  const out = {};
  for (const m of help.matchAll(/<section class="hsec" id="([a-z0-9-]+)">\s*<h2>([\s\S]*?)<\/h2>/g)) {
    const t = new RegExp(`<span data-lng="${lang}">([\\s\\S]*?)</span>`).exec(m[2]);
    if (t) out[m[1]] = strip(t[1]);
  }
  return out;
}
const T = { en: titles('en'), fr: titles('fr') };
// page → help chapter anchor (the chapter that explains that page)
const HELP = { 'index.html': 'helpdesk', 'site-actions.html': 'site-actions', 'inspections.html': 'inspections', 'meetings.html': 'meetings',
  'field/index.html': 'field', 'portfolio.html': 'portfolio', 'cockpit.html': 'cockpit', 'activity-tracker.html': 'tracker', 'assets.html': 'assets',
  'report-studio.html': 'report-studio', 'dashboards.html': 'dashboards', 'analytics.html': 'helpdesk', 'it-review.html': 'executive',
  'integrations.html': 'report-studio', 'system-logs.html': 'admin', 'policies.html': 'policies', 'site-awareness.html': 'executive' };
const ref = (href, lang) => { const n = HELP[href.split(/[?#]/)[0]]; return n && T[lang][n] ? `help.html#${n} — ${T[lang][n]}` : (lang === 'fr' ? 'pas de section d’aide dédiée (à rédiger)' : 'no dedicated help section yet (to write)'); };

function sheet(p) {
  const prof = WP.PROFILES.find((x) => x.id === p.id);
  const L = [`# ${prof.fr} / ${prof.en} — fiche de formation · training sheet`, '',
    '_Générée par `node tools/agent/p09-training.js` à partir de l’aide intégrée et de la liste de tâches du profil._',
    '_Generated by `node tools/agent/p09-training.js` from the in-app help and the profile task list._', '',
    '> Liste de tâches = **proposition de l’agent (IA)**, à confirmer par la cohorte pilote (décision D-P09-4).',
    '> Task list = **AI proposal**, to be confirmed by the pilot cohort (decision D-P09-4).', '',
    '## Français', '', `Rôles : ${p.roles.join(', ')}${p.site ? ' · compte rattaché à un site' : ''}. Page d’arrivée : **Accueil** (\`home.html\`), raccourcis du profil.`, ''];
  p.tasks.forEach((t, i) => { L.push(`${i + 1}. **${t.fr}** — Accueil ▸ raccourci → \`${t.href}\` (1 clic), puis l’action dans la page.`, `   - Aide : ${ref(t.href, 'fr')}`); });
  L.push('', 'À l’issue de la formation, la personne sait faire ces trois tâches seule. Le facilitateur ne note **aucun** résultat ici : les mesures vont dans les fiches du pilote (`T1-T8-SHEET.csv`, `SUS-SHEET.csv`).', '',
    '## English', '', `Roles: ${p.roles.join(', ')}${p.site ? ' · account tied to a site' : ''}. Landing page: **Home** (\`home.html\`), profile shortcuts.`, '');
  p.tasks.forEach((t, i) => { L.push(`${i + 1}. **${t.en}** — Home ▸ shortcut → \`${t.href}\` (1 click), then the action inside the page.`, `   - Help: ${ref(t.href, 'en')}`); });
  L.push('', 'After the session the person can do these three tasks alone. The facilitator records **no** result here: measures go to the pilot sheets (`T1-T8-SHEET.csv`, `SUS-SHEET.csv`).', '');
  return L.join('\n');
}
const dir = path.join(ROOT, 'docs/ops/pilot/training');
const check = process.argv.includes('--check');
let stale = 0;
if (!check) fs.mkdirSync(dir, { recursive: true });
for (const p of PROFILE_TASKS) {
  const f = path.join(dir, p.id + '.md'), out = sheet(p);
  if (check) { if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== out) { stale++; console.error('stale: ' + p.id); } }
  else fs.writeFileSync(f, out);
}
if (check && stale) process.exit(1);
console.log(check ? 'training sheets up to date' : `wrote ${PROFILE_TASKS.length} sheets to docs/ops/pilot/training/`);
