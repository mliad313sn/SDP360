#!/usr/bin/env node
'use strict';
// E-D05 (expert audit 2026-11-05, audit D-07 / K-03 rest / K-06 prep) — metric lineage & contract sheet.
// ONE sheet per registered metric joining what was spread over several places: the registry seed
// (services/metricRegistry.js — names, unit, formula, window, RAG policy, reader + field, owner role,
// certification), the consumers (tools/agent/metric-map.js), the freshness of the sync job feeding it
// (services/sync/jobs.js FRESHNESS_HOURS via services/governancePolicy.js FRESHNESS_SOURCES) and where the
// versioned contract lives (kpi_policies, db 065 — read at run time, never copied here).
//
//   node tools/agent/metric-lineage.js            writes docs/ops/METRIC-LINEAGE.md
//   node tools/agent/metric-lineage.js --check    exits 1 when the committed file is out of date
//
// Nothing here decides anything: certification text is the registry's; the metrics no code names carry a
// decision block "use / archive / reserve — PENDING KPI committee" with no answer filled.

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'docs', 'ops', 'METRIC-LINEAGE.md');
const read = (p) => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const cell = (v) => String(v == null || v === '' ? '—' : v).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (v) => '`' + String(v).replace(/`/g, "'") + '`';

function sourceFile(m, root) {
  const mod = String(m.source || '').split('.')[0];
  if (!mod) return null;
  for (const c of [`${mod}.js`, `services/${mod}.js`]) if (fs.existsSync(path.join(root, c))) return c;
  return null;
}

function build({ root = ROOT } = {}) {
  const { SEED } = require(path.join(root, 'services', 'metricRegistry'));
  const KpiRag = require(path.join(root, 'services', 'kpiRag'));
  const { FRESHNESS_HOURS } = require(path.join(root, 'services', 'sync', 'jobs'));
  const { FRESHNESS_SOURCES } = require(path.join(root, 'services', 'governancePolicy'));
  const jobOf = new Map(FRESHNESS_SOURCES);
  const map = require(path.join(root, 'tools', 'agent', 'metric-map')).build({ root });
  const byKey = new Map(map.rows.map((r) => [r.key, r]));
  const isUnused = (r) => !r || (!r.widgets.length && !r.rules.length && !Object.keys(r.by).some((k) => k !== 'tests'));
  const unused = SEED.filter((m) => isUnused(byKey.get(m.key))).map((m) => m.key);

  const L = [];
  L.push('# Metric lineage & contract sheet — one sheet per registered metric');
  L.push('');
  L.push('Generated by `node tools/agent/metric-lineage.js` from the code (`--check` fails when this file is stale). Do not edit by hand.');
  L.push('');
  L.push('**Versioned contract.** `metric_registry` itself has no version column: the versioned contract of a metric is its');
  L.push('`kpi_policies` row (db 065 — version, effective_from/to, owner, rationale, min_sample, null_handling `unknown`,');
  L.push('immutable once adopted). The adopted version is read at run time (Admin ▸ KPI policies) and is **not** in this file.');
  L.push('Database rows of `metric_registry` / `kpi_rag_policies` win over the code seed shown here.');
  L.push('');
  L.push('**Freshness** = the sync job feeding the module and its declared window (`services/sync/jobs.js`); a governance');
  L.push('`freshness.*_hours` policy can override it at run time. A module with no sync job reads `UNKNOWN`.');
  L.push('');
  L.push(`Metrics: **${SEED.length}** · named by no code outside tests (decision pending): **${unused.length}**`);
  L.push('');
  for (const m of SEED) {
    const r = byKey.get(m.key) || { widgets: [], rules: [], by: {} };
    const pol = m.rag_policy ? KpiRag.POLICIES[m.rag_policy] : null;
    const job = jobOf.get(m.module);
    const fresh = job && FRESHNESS_HOURS[job] ? `${code(job)} — declared window ${FRESHNESS_HOURS[job]} h` : 'UNKNOWN (no sync job feeds this module)';
    const consumers = [
      ...r.widgets.map((w) => 'widget ' + code(w)),
      ...r.rules.map((x) => 'alert rule ' + code(x)),
      ...Object.entries(r.by).filter(([k]) => k !== 'tests').flatMap(([k, files]) => files.map((f) => `${k}: ${code(f)}`)),
    ];
    L.push(`## ${code(m.key)}`);
    L.push('');
    L.push('| Field | Value |');
    L.push('|---|---|');
    L.push(`| Name | ${cell(m.name)} / ${cell(m.name_fr)} |`);
    L.push(`| Module · unit | ${cell(m.module)} · ${cell(m.unit)} |`);
    L.push(`| Source | reader ${code(m.reader)} · field ${code(m.field)} · ${cell(m.source)}${sourceFile(m, root) ? ' (' + code(sourceFile(m, root)) + ')' : ''} |`);
    L.push(`| Formula | ${cell(m.formula)} |`);
    L.push(`| Window kind | ${cell(m.window_kind)} |`);
    L.push(`| RAG policy | ${m.rag_policy ? code(m.rag_policy) + (pol ? ` (code default: scale ${cell(pol.scale)}, green ${cell(pol.green)}, amber ${cell(pol.amber)})` : ' (not defined in code)') : 'none (no colour)'} |`);
    L.push(`| Higher is better | ${m.higher_is_better ? 'yes' : 'no'} |`);
    L.push(`| Owner role | ${cell(m.owner_role)} |`);
    L.push(`| Certification | ${cell(m.certification)} |`);
    L.push(`| Versioned contract | kpi_policies (adopted version read at run time — not in this file) |`);
    L.push(`| Freshness | ${fresh} |`);
    L.push(`| Consumers | ${consumers.length ? consumers.join('<br>') : 'generic consumers only (composer, /api/metrics, external API)'}${r.by.tests ? ` · tests: ${r.by.tests.length} file(s)` : ''} |`);
    L.push('');
    if (unused.includes(m.key)) {
      L.push('> **Decision — use / archive / reserve — PENDING KPI committee.** No widget, alert rule, page or server code names');
      L.push('> this metric. Decision: _(not taken)_ · Decided by: _(not recorded)_ · Date: _(not recorded)_ · Minutes ref: _(not recorded)_');
      L.push('');
    }
  }
  return { markdown: L.join('\n'), unused, keys: SEED.map((m) => m.key) };
}

function main(argv = process.argv.slice(2), { out = OUT, root = ROOT } = {}) {
  const md = build({ root }).markdown;
  if (argv.includes('--check')) {
    const cur = fs.existsSync(out) ? read(out) : '';
    if (cur !== md) { console.error('METRIC-LINEAGE.md is out of date — run: node tools/agent/metric-lineage.js'); return 1; }
    console.log('metric lineage up to date'); return 0;
  }
  fs.writeFileSync(out, md);
  console.log('wrote ' + path.relative(root, out));
  return 0;
}

if (require.main === module) process.exit(main());
module.exports = { build, main, OUT };
