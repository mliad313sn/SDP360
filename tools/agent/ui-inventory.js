#!/usr/bin/env node
'use strict';
// E-V01 — UI & chart inventory. A pure scan of public/*.html and public/lib/*.js that makes today's visual debt
// measurable: page size, inline <style> blocks, hex-colour literals, Chart.js call sites and chart types, dual axes
// (`yAxisID`), doughnut/pie charts, and whether the shared chart/table/state libraries are loaded. Generated, never
// hand-edited, so it cannot drift from the code:
//
//   node tools/agent/ui-inventory.js            writes docs/ux/CHART-INVENTORY.md
//   node tools/agent/ui-inventory.js --check    exits 1 when the committed file is out of date
//
// What it does NOT claim: a count is a literal pattern in the source, not a rendered chart. The "substitution to
// consider" column is a PROPOSAL taken from the audit's measure → chart matrix (§5.2); choosing a substitution is a
// person's decision after a browser review. tests/ui-design-ratchet.test.js keeps these counts from growing.

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'docs', 'ux', 'CHART-INVENTORY.md');

const read = (p) => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const count = (text, re) => (text.match(re) || []).length;

// A colour literal: '#' + 3, 4, 6 or 8 hex digits, not part of an HTML entity (&#123;) nor of a longer word.
const HEX_RE = /(?<![&\w#])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})(?![0-9a-zA-Z_-])/g;
const STYLE_RE = /<style[\s>]/gi;
const NEW_CHART_RE = /new\s+Chart\s*\(/g;
const DUAL_AXIS_RE = /\byAxisID\b/g;
const TYPE_RE = /\btype\s*:\s*['"](bar|line|doughnut|pie|radar|polarArea|scatter|bubble)['"]/g;
const DOUGHNUT_RE = /['"](doughnut|pie)['"]/g;

function scanText(text) {
  const types = {};
  let m;
  TYPE_RE.lastIndex = 0;
  while ((m = TYPE_RE.exec(text))) types[m[1]] = (types[m[1]] || 0) + 1;
  return {
    bytes: Buffer.byteLength(text, 'utf8'),
    styleBlocks: count(text, STYLE_RE),
    hex: count(text, HEX_RE),
    newChart: count(text, NEW_CHART_RE),
    types,
    dualAxis: count(text, DUAL_AXIS_RE),
    doughnut: count(text, DOUGHNUT_RE),
    chartTheme: /chartTheme\.js/.test(text),
    chartTable: /ChartTable/.test(text),
    pageStates: /pageStates\.js/.test(text),
  };
}

// §5.2 measure → chart matrix, turned into proposal wording for what a page already contains.
function substitution(s) {
  const out = [];
  if (s.dualAxis) out.push('dual axis → small multiples, one unit per panel (§5.2 "comparaison à plusieurs séries")');
  if (s.doughnut) out.push('doughnut/pie → ordered horizontal bars with values and population % (§5.2 "répartition de catégories")');
  if (s.newChart && !s.chartTable) out.push('chart without a data table → add ChartTable (same population and period)');
  if (s.hex) out.push('hex literals → _tokens.css variables');
  return out.length ? out.join('; ') : '—';
}

function listFiles(root) {
  const pub = path.join(root, 'public');
  const lib = path.join(pub, 'lib');
  const html = fs.existsSync(pub) ? fs.readdirSync(pub).filter((f) => /\.html$/.test(f)).sort().map((f) => 'public/' + f) : [];
  const js = fs.existsSync(lib) ? fs.readdirSync(lib).filter((f) => /\.js$/.test(f)).sort().map((f) => 'public/lib/' + f) : [];
  return html.concat(js);
}

function build({ root = ROOT, files } = {}) {
  const list = files || listFiles(root);
  const rows = list.map((file) => Object.assign({ file }, scanText(read(path.join(root, file)))));
  const L = [];
  const yes = (b) => (b ? 'yes' : '—');
  const types = (t) => Object.keys(t).sort().map((k) => `${k}×${t[k]}`).join(' ') || '—';
  const sum = (k) => rows.reduce((a, r) => a + r[k], 0);
  L.push('# UI & chart inventory — generated — do not edit');
  L.push('');
  L.push('Generated by `node tools/agent/ui-inventory.js` from `public/*.html` and `public/lib/*.js` (`--check` fails when this');
  L.push('file is stale). Counts are literal patterns in the source, not rendered charts. `tests/ui-design-ratchet.test.js`');
  L.push('records a per-page budget for hex literals, dual axes and doughnuts: those can only go down.');
  L.push('');
  L.push('The "substitution to consider" column is a **proposal** worded from the audit\'s measure → chart matrix (§5.2).');
  L.push('Choosing and approving a substitution is a person\'s decision after a browser review; nothing here is decided.');
  L.push('');
  L.push(`Files scanned: **${rows.length}** · inline <style> blocks: **${sum('styleBlocks')}** · hex literals: **${sum('hex')}** · \`new Chart(\` call sites: **${sum('newChart')}** · dual axes (\`yAxisID\`): **${sum('dualAxis')}** · doughnut/pie: **${sum('doughnut')}**`);
  L.push('');
  L.push('| File | Bytes | <style> | Hex | new Chart( | Chart types | Dual axis | Doughnut/pie | chartTheme.js | ChartTable | pageStates.js | Substitution to consider |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    L.push(`| \`${r.file}\` | ${r.bytes} | ${r.styleBlocks} | ${r.hex} | ${r.newChart} | ${types(r.types)} | ${r.dualAxis} | ${r.doughnut} | ${yes(r.chartTheme)} | ${yes(r.chartTable)} | ${yes(r.pageStates)} | ${substitution(r)} |`);
  }
  L.push('');
  return { markdown: L.join('\n'), rows };
}

// Ratchet: a page may not exceed its recorded budget. Returns the list of breaches (empty = ok).
const RATCHET_KEYS = ['hex', 'dualAxis', 'doughnut'];
function checkBudgets(rows, budgets) {
  const breaches = [];
  for (const r of rows) {
    const b = budgets[r.file] || {};
    for (const k of RATCHET_KEYS) {
      const allowed = b[k] || 0;
      if (r[k] > allowed) breaches.push({ file: r.file, key: k, allowed, got: r[k] });
    }
  }
  return breaches;
}

function main(argv = process.argv.slice(2)) {
  const md = build().markdown;
  if (argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? read(OUT) : '';
    if (cur !== md) { console.error('CHART-INVENTORY.md is out of date — run: node tools/agent/ui-inventory.js'); return 1; }
    console.log('chart inventory up to date'); return 0;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, md);
  console.log('wrote ' + path.relative(ROOT, OUT));
  return 0;
}

if (require.main === module) process.exit(main());
module.exports = { build, main, scanText, checkBudgets, substitution, RATCHET_KEYS, OUT, HEX_RE };
