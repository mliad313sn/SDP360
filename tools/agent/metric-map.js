#!/usr/bin/env node
'use strict';
// C-25 (G01) — metric → widget map. For every metric of the registry seed (services/metricRegistry.js) it lists
// where the key is used: shipped dashboard widgets (services/dashboardSeeds.js), alert rules
// (services/alertRulesSeed.js), pages and browser libraries (public/), server code and exports (services/,
// routes/, *.js), and the tests that name it. Generated, never hand-edited, so it cannot drift from the code:
//
//   node tools/agent/metric-map.js            writes docs/ops/METRIC-WIDGET-MAP.md
//   node tools/agent/metric-map.js --check    exits 1 when the committed file is out of date
//
// What it does NOT claim: a reference is a literal key in the source. The generic consumers (composer,
// /api/metrics, the external API, Report Studio) can serve ANY metric at run time and are listed once, apart.
// "Used by a widget" is not "the figure is right" — correctness lives in the tests and in human review.

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'docs', 'ops', 'METRIC-WIDGET-MAP.md');

const read = (p) => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
function walk(dir, re, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (e.name === 'node_modules' || e.name === 'vendor' || e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, re, out); else if (re.test(e.name)) out.push(p);
  }
  return out;
}
const rel = (root, p) => path.relative(root, p).split(path.sep).join('/');
const esc = (k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const keyRe = (k) => new RegExp('(^|[^\\w.])' + esc(k) + '(?![\\w.])');

// Files that only DEFINE metrics or serve any of them generically — listed once, never per metric.
const DEFINERS = new Set(['services/metricRegistry.js', 'tools/agent/metric-map.js']);
const GENERIC = [
  ['routes/metrics.js', 'GET /api/metrics/* — resolves any registered key'],
  ['routes/dashboards.js', 'dashboard viewer/composer API — any metric a published definition names'],
  ['routes/extApi.js', 'external API — any registered key'],
  ['routes/reportStudio.js', 'Report Studio — figures of the dashboards/templates it renders'],
  ['services/reportPack.js', 'report pack exports (HTML/CSV/XLSX/PPTX) — every figure of a pack'],
  ['public/dashboards.html', 'dashboard viewer page — renders any published definition'],
  ['public/dashboard-composer.html', 'composer — metric picker lists every registered key'],
];

function classify(file) {
  if (/^tests\//.test(file)) return 'tests';
  if (/^public\/.*\.html$/.test(file)) return 'pages';
  if (/^public\//.test(file)) return 'browser libraries';
  if (/(pptx|excel|xlsx|csv|export|reportPack|reportTemplates|send[A-Z])/i.test(file) || /^tools\/(reports|exec-pptx)\//.test(file)) return 'exports';
  if (/^routes\//.test(file)) return 'API routes';
  return 'server code';
}

function build({ root = ROOT } = {}) {
  const { SEED } = require(path.join(root, 'services', 'metricRegistry'));
  const { SEED_DASHBOARDS } = require(path.join(root, 'services', 'dashboardSeeds'));
  const { SEED_RULES: alerts } = require(path.join(root, 'services', 'alertRulesSeed'));
  const files = [];
  for (const d of ['services', 'routes', 'public', 'tools', 'tests']) walk(path.join(root, d), /\.(js|html|json|mjs)$/, files);
  for (const f of fs.readdirSync(root)) if (/\.js$/.test(f)) files.push(path.join(root, f));
  const sources = files.map((p) => ({ file: rel(root, p), text: read(p) })).filter((s) => !DEFINERS.has(s.file) && !/\.suite-manifest\.json$/.test(s.file));

  const rows = [];
  for (const m of SEED) {
    const widgets = [];
    for (const d of SEED_DASHBOARDS) for (const w of d.widgets || []) if (w.metric === m.key) widgets.push(`${d.key}#${w.id} (${w.type})`);
    const rules = alerts.filter((a) => a && a.metric === m.key).map((a) => a.key);
    const re = keyRe(m.key);
    const by = {};
    for (const s of sources) {
      if (s.file === 'services/dashboardSeeds.js' || s.file === 'services/alertRulesSeed.js') continue;
      if (!re.test(s.text)) continue;
      (by[classify(s.file)] = by[classify(s.file)] || []).push(s.file);
    }
    rows.push({ key: m.key, module: m.module, unit: m.unit, widgets, rules, by });
  }

  const code = (v) => '`' + v + '`';
  const list = (a) => (a && a.length ? a.map(code).join('<br>') : '—');
  const L = [];
  L.push('# Metric → widget map — where each registered metric is used');
  L.push('');
  L.push('Generated by `node tools/agent/metric-map.js` from the code (`--check` fails when this file is stale). Do not edit by hand.');
  L.push('');
  L.push('Evidence level: **code** (a literal key reference). A reference proves usage, not correctness; browser review and');
  L.push('human acceptance of each figure are separate and are not recorded here.');
  L.push('');
  const unused = rows.filter((r) => !r.widgets.length && !r.rules.length && !Object.keys(r.by).some((k) => k !== 'tests'));
  L.push(`Metrics in the registry seed: **${rows.length}** · on a shipped dashboard widget: **${rows.filter((r) => r.widgets.length).length}** · in an alert rule: **${rows.filter((r) => r.rules.length).length}** · named by no code outside tests (reachable only through the generic consumers): **${unused.length}**`);
  L.push('');
  L.push('## Generic consumers (can serve any registered metric at run time)');
  L.push('');
  L.push('| File | Role |');
  L.push('|---|---|');
  for (const [f, r] of GENERIC) if (fs.existsSync(path.join(root, f))) L.push(`| ${code(f)} | ${r} |`);
  L.push('');
  L.push('## Per metric');
  L.push('');
  L.push('| Metric | Module | Unit | Dashboard widgets (dashboard#widget) | Alert rules | Pages | Browser libraries | Exports | API routes | Server code | Tests |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    L.push(`| ${code(r.key)} | ${r.module} | ${r.unit} | ${list(r.widgets)} | ${list(r.rules)} | ${list(r.by.pages)} | ${list(r.by['browser libraries'])} | ${list(r.by.exports)} | ${list(r.by['API routes'])} | ${list(r.by['server code'])} | ${r.by.tests ? r.by.tests.length + ' file(s)' : '—'} |`);
  }
  L.push('');
  if (unused.length) {
    L.push('## Metrics named by no widget, rule, page or server code');
    L.push('');
    L.push('Not an error: they remain available to the composer and the APIs. Listed so a reviewer can decide whether each is needed.');
    L.push('');
    for (const r of unused) L.push(`- ${code(r.key)}`);
    L.push('');
  }
  return { markdown: L.join('\n'), rows };
}

function main(argv = process.argv.slice(2)) {
  const md = build().markdown;
  if (argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? read(OUT) : '';
    if (cur !== md) { console.error('METRIC-WIDGET-MAP.md is out of date — run: node tools/agent/metric-map.js'); return 1; }
    console.log('metric-widget map up to date'); return 0;
  }
  fs.writeFileSync(OUT, md);
  console.log('wrote ' + path.relative(ROOT, OUT));
  return 0;
}

if (require.main === module) process.exit(main());
module.exports = { build, main, classify, keyRe, OUT };
