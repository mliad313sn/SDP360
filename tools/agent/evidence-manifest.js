#!/usr/bin/env node
'use strict';
// C-25 (G01) — evidence manifest: a SHA-256 of every evidence file (docs/agent-execution/*.md) and of every
// generated register, plus the evidence LEVEL each goal file may claim. An agent can only produce
// "code+test"; "browser-checked" and "human-accepted" are recorded by a person and are listed as pending.
//
//   node tools/agent/evidence-manifest.js            writes docs/agent-execution/EVIDENCE-MANIFEST.md
//   node tools/agent/evidence-manifest.js --check    exits 1 when a listed file changed, appeared or vanished
//
// The manifest is a point-in-time seal: regenerate it after a reviewed merge (like INVENTORY.*). A failing
// --check means "the evidence on disk is not the evidence that was sealed", never that the evidence is wrong.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.join(__dirname, '..', '..');
const MANIFEST = 'docs/agent-execution/EVIDENCE-MANIFEST.md';

// Generated registers sealed alongside the evidence (each has its own --check generator).
const REGISTERS = [
  'docs/agent-execution/INVENTORY.json',
  'docs/agent-execution/INVENTORY.md',
  'docs/agent-execution/TRACEABILITY.md',
  'docs/ops/AUTHZ-MATRIX.md',
  'docs/ops/FLAG-REGISTER.md',
  'docs/ops/METRIC-WIDGET-MAP.md',
];
const LEVELS = ['code+test', 'browser-checked', 'human-accepted'];

const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
// Line endings are normalised so a Windows checkout (core.autocrlf) seals the same bytes as Linux.
const norm = (p) => Buffer.from(fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n'), 'utf8');

function collect(root = ROOT) {
  const dir = path.join(root, 'docs', 'agent-execution');
  const evidence = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.md$/.test(f)).sort()
    .map((f) => 'docs/agent-execution/' + f).filter((f) => f !== MANIFEST && !REGISTERS.includes(f)) : [];
  const regs = REGISTERS.filter((f) => fs.existsSync(path.join(root, f)));
  return {
    evidence: evidence.map((f) => ({ file: f, sha256: sha(norm(path.join(root, f))) })),
    registers: regs.map((f) => ({ file: f, sha256: sha(norm(path.join(root, f))) })),
  };
}

// A goal evidence file is named after its goal id (A-01.md, C-25.md, G07.md…); other files are reference notes.
const goalOf = (file) => { const m = /\/([A-Z]-?\d{2}[a-z]?)(?:[-.]|\.md$)/.exec(file); return m ? m[1] : null; };

function build({ root = ROOT } = {}) {
  const { evidence, registers } = collect(root);
  const L = [];
  L.push('# Evidence manifest — checksums and evidence levels');
  L.push('');
  L.push('Generated by `node tools/agent/evidence-manifest.js` (`--check` fails when a sealed file changed). Do not edit by hand.');
  L.push('SHA-256 over the file with line endings normalised to LF.');
  L.push('');
  L.push('## Evidence levels');
  L.push('');
  L.push('- **code+test** — the change is in the code and named tests pass. The ONLY level an agent may claim.');
  L.push('- **browser-checked** — a person exercised the screen in a browser. Recorded by that person; pending until then.');
  L.push('- **human-accepted** — the accountable owner accepted the outcome (UAT, PO, committee). Pending until recorded.');
  L.push('');
  L.push('No row below is browser-checked or human-accepted: nothing in this repository records such a check by a person.');
  L.push('An evidence file that says "verified in the browser" describes an agent run on a throwaway instance, which is');
  L.push('not the browser-checked level.');
  L.push('');
  L.push('## Goal evidence files');
  L.push('');
  L.push('| File | Goal | Level claimed | browser-checked | human-accepted | SHA-256 |');
  L.push('|---|---|---|---|---|---|');
  for (const e of evidence) {
    const g = goalOf(e.file);
    L.push(`| \`${e.file}\` | ${g || '— (reference)'} | ${g ? 'code+test' : '—'} | ${g ? 'pending' : '—'} | ${g ? 'pending' : '—'} | \`${e.sha256}\` |`);
  }
  L.push('');
  L.push('## Generated registers');
  L.push('');
  L.push('| File | SHA-256 |');
  L.push('|---|---|');
  for (const r of registers) L.push(`| \`${r.file}\` | \`${r.sha256}\` |`);
  L.push('');
  return L.join('\n');
}

/** Parse a committed manifest back into { file → sha256 }. */
function parse(text) {
  const out = new Map();
  for (const line of String(text).split('\n')) {
    const m = /^\|\s*`([^`]+)`.*\|\s*`([0-9a-f]{64})`\s*\|\s*$/.exec(line);
    if (m) out.set(m[1], m[2]);
  }
  return out;
}

/** Differences between the sealed manifest and the files on disk. Empty array = sealed. */
function check({ root = ROOT } = {}) {
  const p = path.join(root, MANIFEST);
  if (!fs.existsSync(p)) return [{ file: MANIFEST, problem: 'manifest missing' }];
  const sealed = parse(fs.readFileSync(p, 'utf8'));
  const { evidence, registers } = collect(root);
  const now = new Map([...evidence, ...registers].map((x) => [x.file, x.sha256]));
  const diffs = [];
  for (const [f, h] of sealed) {
    if (!now.has(f)) diffs.push({ file: f, problem: 'missing on disk' });
    else if (now.get(f) !== h) diffs.push({ file: f, problem: 'checksum changed' });
  }
  for (const f of now.keys()) if (!sealed.has(f)) diffs.push({ file: f, problem: 'not in manifest' });
  return diffs;
}

function main(argv = process.argv.slice(2), { root = ROOT } = {}) {
  if (argv.includes('--check')) {
    const d = check({ root });
    if (d.length) { for (const x of d) console.error(`${x.problem}: ${x.file}`); console.error('evidence manifest out of date — review, then run: node tools/agent/evidence-manifest.js'); return 1; }
    console.log('evidence manifest sealed'); return 0;
  }
  fs.writeFileSync(path.join(root, MANIFEST), build({ root }));
  console.log('wrote ' + MANIFEST);
  return 0;
}

if (require.main === module) process.exit(main());
module.exports = { build, check, parse, main, collect, goalOf, LEVELS, REGISTERS, MANIFEST };
