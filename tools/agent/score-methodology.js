'use strict';
// E-G05 (audit G-05 prep; decision D-03 stays with the KPI committee) — the site score methodology, GENERATED from
// the code so the published page cannot drift from what is computed:
//
//   node tools/agent/score-methodology.js            writes docs/ops/SCORE-METHODOLOGY.md
//   node tools/agent/score-methodology.js --check    exits 1 when the committed file is out of date
//
// Every value below is READ from the modules (thresholds, bands, weights, window, switch, models) or quoted from
// their source (the composite formula lines) — nothing is retyped. Nothing is certified: no KPI committee approval
// is recorded (G06), and the page says so.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'docs', 'ops', 'SCORE-METHODOLOGY.md');

function compositeFormulaLines() {
  const src = fs.readFileSync(path.join(ROOT, 'services', 'siteComposite.js'), 'utf8').replace(/\r\n/g, '\n');
  const a = src.indexOf('function composite('); const b = src.indexOf('\n}\n', a);
  if (a < 0 || b < 0) throw new Error('composite() not found in services/siteComposite.js');
  const body = src.slice(a, b);
  const pick = (re) => { const m = body.match(re); if (!m) throw new Error('composite formula line not found: ' + re); return m[0].trim(); };
  return [pick(/const del = [^\n]+/), pick(/const gov = [^\n]+/), pick(/const eng = [^\n]+/), pick(/const score = [^\n;]+/)];
}

function build() {
  const S = require('../../services/siteScore');
  const SB = require('../../services/siteScoreboard');
  const C = require('../../services/siteComposite');
  const W = require('../../services/scoreWindow');
  const PS = require('../../services/publishedSiteScore');
  const { POLICIES } = require('../../services/kpiRag');
  const { DEFAULTS } = require('../../services/reportConfig');
  const reg = require('../../services/metricRegistry').current();
  const cert = (k) => { try { const m = reg.get(k); return (m && m.certification) || 'not certified'; } catch (_) { return 'not certified'; } };
  const maxPts = S.PT_THRESHOLDS.length * 2;
  const win = W.rollingWindow('2026-06-30');   // the default window length, read by calling the function
  const months = (Number(win.to.slice(0, 4)) - Number(win.from.slice(0, 4))) * 12 + Number(win.to.slice(5, 7)) - Number(win.from.slice(5, 7));
  const pct = (w) => `${Math.round(w * 100)} %`;
  const band = (p) => `GREEN ≥ ${p.green} · AMBER ${p.amber}–${p.green - 1} · RED < ${p.amber}`;
  const L = [];
  L.push('# Site score methodology', '',
    'Generated by `node tools/agent/score-methodology.js` from the code (`--check` fails when a constant changes and this',
    'page was not regenerated). **Nothing here is certified**: no KPI-committee approval is recorded (G06), and the choice of',
    'the reference site score is decision **D-03 — OPEN**.', '');
  L.push('## 1. Programme score (`services/siteScore.js`, the author\'s sbDims model)', '',
    `${S.PT_THRESHOLDS.length} dimensions × 0/1/2 points; score = round(points ÷ ${maxPts} × 100). Bands (registry policy \`site-score\`): ${band(POLICIES['site-score'])}.`,
    `Window: rolling ${months} months ending at the as-of date (\`services/scoreWindow.js\` rollingWindow, e.g. ${win.from} → ${win.to}).`, '',
    '| Dimension | 2 points (green) | 1 point (amber) | Direction | Definition |', '|---|---|---|---|---|');
  for (const [key, label, g, a, invert, , tip] of S.PT_THRESHOLDS) {
    L.push(`| ${label} (\`${key}\`) | ${invert ? '≤ ' : '≥ '}${g} | ${invert ? '≤ ' : '≥ '}${a} | ${invert ? 'lower is better' : 'higher is better'} | ${tip} |`);
  }
  L.push('', '**Applicability gate** (`hasData`): a site with no measured input on the window is **non applicable** (score, RAG and',
    'trend null), never a graded RED — two dimensions are inverted, so absence of data would otherwise look like excellence.',
    '`raised` (issues raised) is read only to tell a measured 0 % resolution from "no issue raised"; it is never scored.', '',
    `Certification: ${cert('programme.site_score')}.`, '');
  L.push('## 2. Operational composite (`services/siteComposite.js`)', '',
    `Bands (registry policy \`site-composite\`): ${band(POLICIES['site-composite'])}. Formula, quoted from the source:`, '', '```js', ...compositeFormulaLines(), '```', '',
    `Not per-site isolated: the fleet median resolution time is part of the score. Default anchor date \`${C.ANCHOR}\`. Known`,
    'quirks (no ceiling, uncapped penalty, defaults on empty data) are listed at the top of the module and are kept as ported.', '');
  L.push('## 3. Operational scoreboard (`services/siteScoreboard.js`)', '',
    '| Dimension | Weight |', '|---|---|');
  for (const [d, w] of Object.entries(SB.WEIGHTS)) L.push(`| ${d} | ${pct(w)} |`);
  L.push('', 'Weights are **renormalised over the dimensions present** (a missing dimension is null, excluded — never 0);',
    `coverage = present / ${Object.keys(SB.WEIGHTS).length}; no dimension present = non applicable. Bands: \`site-composite\` (${band(POLICIES['site-composite'])}).`, '',
    `Certification: ${cert('programme.composite')}.`, '');
  L.push('## 4. Which score is published', '',
    `\`report_config\` \`site_score_published_model\` — default \`${DEFAULTS.site_score_published_model}\` (today: each e-mail keeps its own model). Values: ${PS.MODELS.map((m) => '`' + m + '`').join(', ')}.`,
    'The switch only chooses which already-computed result is shown first; the other is carried alongside as "non publié".', '');
  L.push('## 5. Where the history lives', '',
    '- KPI definitions and their adoption: `kpi_policies` (migration 065, `services/kpiPolicyStore.js`) — draft → proposed → adopted',
    '  by a committee member who is not the author; adopted versions are immutable; every step appends a history row.',
    '- Governance rules (thresholds of the regulation behaviours): `services/governancePolicy.js`, append-only history',
    '  shown on Admin ▸ Governance policies.',
    '- Switch values: `report_config` (who changed what and when: `updated_by`, `updated_at`), listed in `docs/ops/FLAG-REGISTER.md`.', '');
  L.push('## Open questions for the KPI committee', '',
    '1. D-03: which of the two scores is the reference published to sites?',
    '2. Are the thresholds and weights above adopted as they are, and who signs the adoption?', '');
  return L.join('\n');
}

if (require.main === module) {
  const text = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== text) { console.error('docs/ops/SCORE-METHODOLOGY.md is out of date — run node tools/agent/score-methodology.js'); process.exit(1); }
    console.log('SCORE-METHODOLOGY.md up to date');
  } else { fs.writeFileSync(OUT, text); console.log('written docs/ops/SCORE-METHODOLOGY.md'); }
}
module.exports = { build, OUT, compositeFormulaLines };
