'use strict';
// Renders tools/qa/route-matrix.js JSON as docs/remediation/RBAC-MATRIX.md.
// Development evidence only — a probe status is NOT proof of correct authorization.
const fs = require('fs');
const rows = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const den = (s) => s === 401 || s === 403;
const GUARDS = /^(require[A-Za-z]+|requireRole\[.*\])$/;
const moduleOf = (p) => { const seg = String(p || '').split('/'); if (seg[1] !== 'api') return '(page)'; return seg[2] === 'reports' && seg[3] && !seg[3].startsWith(':') ? 'reports/' + seg[3] : seg[2]; };
const api = rows.filter((r) => r.none !== undefined);
const byMod = {};
for (const r of api) (byMod[moduleOf(r.path)] = byMod[moduleOf(r.path)] || []).push(r);
const anonOpen = api.filter((r) => !den(r.none));
const keyOpen = api.filter((r) => den(r.none) && !den(r.dashkey));
const noGuard = api.filter((r) => !r.chain.some((n) => GUARDS.test(n)));
let md = `# RBAC-MATRIX — API route × caller probe (M00 Phase 0 / M02 input)

> **Status: TESTED_SYNTHETICALLY.** Generated by \`node tools/qa/route-matrix.js out.json && node tools/qa/route-matrix-md.js out.json\`
> against a throwaway sqlite data dir. A non-401/403 status only means the request **reached the handler**
> (it may then 400/404/500 on fake ids). It is not proof that the handler enforces site/object scope.
> Persona × site × object coverage (M02 step 2) is NOT in this file yet.

Generated: ${new Date().toISOString().slice(0, 10)} · routes registered: ${rows.length} · /api routes probed: ${api.length}

Callers: **none** = no credentials · **dashkey** = only \`x-dash-key\` · **viewer** = valid session, role \`viewer\`.

## Summary

| Check | Count | Disposition |
|---|---|---|
| Anonymous reaches handler | ${anonOpen.length} | must equal the PUBLIC allow-list in \`tests/route-authz.smoke.test.js\` |
| Dash key alone reaches handler | ${keyOpen.length} | gate-only routes; key no longer leaked to anonymous visitors (F-M02-001) — still a shared bearer secret (see RISKS R-02) |
| Route with no named guard middleware in its chain | ${noGuard.length} | relies on the global /api gate and/or an in-handler check — needs per-handler review (WP-M02-002) |

### Anonymous-reachable
${anonOpen.map((r) => `- \`${r.method} ${r.path}\` → ${r.none}`).join('\n')}

### Dash-key-only reachable
${keyOpen.map((r) => `- \`${r.method} ${r.path}\` → ${r.dashkey}`).join('\n')}

## Per module
`;
for (const m of Object.keys(byMod).sort()) {
  md += `\n### ${m} (${byMod[m].length})\n\n| Method | Path | Guard chain | none | dashkey | viewer |\n|---|---|---|---|---|---|\n`;
  for (const r of byMod[m]) md += `| ${r.method} | \`${r.path}\` | ${r.chain.filter((n) => n !== 'anonymous' && n !== '<anonymous>').join(' → ') || '—'} | ${r.none} | ${r.dashkey} | ${r.viewer} |\n`;
}
process.stdout.write(md);
