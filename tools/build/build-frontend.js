'use strict';
// SDP-DASH-2.0 step 5 — ahead-of-time JSX compilation (esbuild), replacing Babel in the browser.
//
//   node tools/build/build-frontend.js           compile every entry
//   node tools/build/build-frontend.js --check   exit 1 when a compiled file is stale (CI)
//
// Each .jsx is TRANSFORMED, not bundled: the output is a classic script, so the top-level
// names the files share today (one page loads several .jsx that see each other's functions)
// keep working exactly as they did under <script type="text/babel">. JSX → React.createElement
// (classic runtime), the same thing Babel's react preset produced.
//
// The compiled .js files are committed: production has no build step, the deploy ZIP copies
// them like any other file. tests/frontend-build.test.js fails when one is out of date.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');

// Pages compiled ahead of time.
const ENTRIES = [
  'public/activity-tracker/App.jsx',
  'public/dashboard-preview/tweaks-panel.jsx',
  'public/dashboard-preview/components.jsx',
  'public/dashboard-preview/App.jsx',
];

function outPath(src) { return src.replace(/\.jsx$/, '.js'); }

function compile(src) {
  const esbuild = require('esbuild');
  const code = fs.readFileSync(path.join(ROOT, src), 'utf8');
  const res = esbuild.transformSync(code, {
    loader: 'jsx', jsx: 'transform', jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment', target: 'es2019', sourcefile: path.basename(src),
    legalComments: 'inline', charset: 'utf8',
  });
  return `// GENERATED by tools/build/build-frontend.js from ${path.basename(src)} — do not edit.\n` + res.code;
}

function main(argv) {
  const check = argv.includes('--check');
  const stale = [];
  for (const src of ENTRIES) {
    const out = path.join(ROOT, outPath(src));
    const next = compile(src);
    const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : null;
    if (prev === next) continue;
    if (check) { stale.push(outPath(src)); continue; }
    fs.writeFileSync(out, next);
    console.log(`[build] ${src} → ${outPath(src)}`);
  }
  if (check && stale.length) {
    console.error('[build] stale compiled files (run: npm run build):\n  ' + stale.join('\n  '));
    return 1;
  }
  return 0;
}

module.exports = { ENTRIES, outPath, compile };
if (require.main === module) process.exit(main(process.argv.slice(2)));
