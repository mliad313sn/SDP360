'use strict';
// E-A04 (audit A-04, baseline part) — measured performance baseline, REPORT ONLY.
//
// Reads the browser-journey artefacts that tools/test/run-e2e.js already writes (one JSON per journey per
// run, `run<i>-<journey>.json`, each holding per-page transfer bytes, DOMContentLoaded and load times) and
// prints p50 / p95 per page path and per journey. It never fails a build and never writes a threshold:
// the "Budget" column is `UNKNOWN — to be approved` for every row. Throwaway database, synthetic data —
// these figures are an observation of this machine, not a budget and not a production measurement.
//
//   node tools/test/perf-baseline.js [--dir=e2e-artifacts] [--out=docs/agent-execution/PERF-BASELINE.md] [--print]
//   (run-e2e.js calls it with --baseline)
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const BUDGET = 'UNKNOWN — to be approved';

/** Nearest-rank percentile; null for an empty list (never 0). */
function percentile(values, p) {
  const v = values.filter((x) => typeof x === 'number' && Number.isFinite(x)).sort((a, b) => a - b);
  if (!v.length) return null;
  const rank = Math.ceil((p / 100) * v.length);
  return v[Math.min(v.length, Math.max(1, rank)) - 1];
}
const stat = (values) => ({ n: values.filter((x) => typeof x === 'number' && Number.isFinite(x)).length, p50: percentile(values, 50), p95: percentile(values, 95) });

/** Load every run<i>-*.json artefact of a directory (summary.json and sub-folders ignored). */
function loadArtefacts(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => /^run\d+-.+\.json$/.test(f)).sort().map((f) => {
    const a = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    a.__run = Number(/^run(\d+)-/.exec(f)[1]);
    return a;
  });
}

/** Pure aggregation: artefacts → { runs, pages:{path:stats}, journeys:{name:stats} }. */
function aggregate(artefacts) {
  const pages = {}; const journeys = {}; const runs = new Set();
  for (const a of artefacts || []) {
    if (typeof a.journey !== 'string') continue;        // a side record (e.g. uat-<seat>.json) is not a journey
    if (a.status && a.status !== 'passed') continue;   // a failed journey is not a timing sample
    if (a.__run != null) runs.add(a.__run);
    const j = (journeys[a.journey] = journeys[a.journey] || { duration: [], pages: [] });
    const t0 = Date.parse(a.started_at); const t1 = Date.parse(a.finished_at);
    if (Number.isFinite(t0) && Number.isFinite(t1) && t1 >= t0) j.duration.push(t1 - t0);
    j.pages.push((a.pages || []).length);
    for (const p of a.pages || []) {
      const k = p.path || p.label || '?';
      const s = (pages[k] = pages[k] || { dcl: [], load: [], bytes: [], fu: [] });
      s.dcl.push(p.dom_content_loaded_ms); s.load.push(p.load_ms); s.bytes.push(p.transfer_bytes); s.fu.push(p.first_usable_ms);
    }
  }
  const out = { runs: runs.size, samples: (artefacts || []).length, pages: {}, journeys: {} };
  for (const [k, s] of Object.entries(pages).sort()) out.pages[k] = { dcl_ms: stat(s.dcl), load_ms: stat(s.load), first_usable_ms: stat(s.fu), transfer_bytes: stat(s.bytes), budget: BUDGET };
  for (const [k, s] of Object.entries(journeys).sort()) out.journeys[k] = { duration_ms: stat(s.duration), pages: stat(s.pages), budget: BUDGET };
  return out;
}

function machine() {
  let commit = 'UNKNOWN';
  try { commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim(); } catch (_) { /* not a git checkout */ }
  const cpu = os.cpus()[0];
  return { commit, node: process.version, platform: `${os.platform()} ${os.release()}`, cpu: cpu ? `${cpu.model} × ${os.cpus().length}` : 'UNKNOWN', memory_gb: Math.round(os.totalmem() / 1e9) };
}

const fmt = (v) => (v == null ? '—' : String(v));
const kb = (v) => (v == null ? '—' : (v / 1024).toFixed(0));
function renderMarkdown(agg, meta = {}) {
  const L = [];
  L.push('# Performance baseline — observation, not a budget (E-A04)');
  L.push('');
  L.push('> **Throwaway database, synthetic data — observation, not a budget.** Generated by `tools/test/perf-baseline.js`');
  L.push('> from the browser-journey artefacts of `tools/test/run-e2e.js`. No threshold is set here: every "Budget"');
  L.push('> cell is `UNKNOWN — to be approved`. A budget is a decision for the product owner, with production-like data.');
  L.push('');
  L.push(`- Generated: ${meta.generated_at || new Date().toISOString()}`);
  L.push(`- Commit: ${meta.commit || 'UNKNOWN'} · Node ${meta.node || 'UNKNOWN'} · ${meta.platform || ''}`);
  L.push(`- Machine: ${meta.cpu || 'UNKNOWN'} · ${meta.memory_gb != null ? meta.memory_gb + ' GB RAM' : 'RAM UNKNOWN'}`);
  L.push(`- Runs: ${agg.runs} · journey samples: ${agg.samples}${meta.source ? ` · artefacts: \`${meta.source}\`` : ''}`);
  L.push('- Percentiles: nearest rank over every sample; `n` = number of samples.');
  L.push('');
  L.push('## Per page (local Chromium, localhost)');
  L.push('');
  L.push('| Page | n | DCL p50 (ms) | DCL p95 (ms) | Load p50 (ms) | Load p95 (ms) | First usable p50 (ms) | First usable p95 (ms) | Transfer p50 (KB) | Transfer p95 (KB) | Budget |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const [k, s] of Object.entries(agg.pages)) { const fu = s.first_usable_ms || { p50: null, p95: null }; L.push(`| \`${k}\` | ${s.dcl_ms.n} | ${fmt(s.dcl_ms.p50)} | ${fmt(s.dcl_ms.p95)} | ${fmt(s.load_ms.p50)} | ${fmt(s.load_ms.p95)} | ${fmt(fu.p50)} | ${fmt(fu.p95)} | ${kb(s.transfer_bytes.p50)} | ${kb(s.transfer_bytes.p95)} | ${s.budget} |`); }
  L.push('');
  L.push('"First usable" = the page\'s `sdp:first-usable` performance mark: its primary table or figure shows data or an explicit state (F-UX-05). `—` = the page sets no mark or no sample — never 0. The vision\'s "< 3 s to first usable table" is a budget for a person to approve.');
  L.push('');
  L.push('## Per journey (wall clock, includes the scripted waits)');
  L.push('');
  L.push('| Journey | n | Duration p50 (ms) | Duration p95 (ms) | Pages measured | Budget |');
  L.push('|---|---|---|---|---|---|');
  for (const [k, s] of Object.entries(agg.journeys)) L.push(`| ${k} | ${s.duration_ms.n} | ${fmt(s.duration_ms.p50)} | ${fmt(s.duration_ms.p95)} | ${fmt(s.pages.p50)} | ${s.budget} |`);
  L.push('');
  L.push('## What this is not');
  L.push('');
  L.push('- Not a production measurement: one machine, localhost, a disposable PostgreSQL database with synthetic rows.');
  L.push('- Not a gate: CI prints this table and never fails on it.');
  L.push('- Not a budget: a person sets budgets after a measurement on production-like volumes (see `docs/agent-execution/EXPLAIN-SYNTHETIC.md`).');
  return L.join('\n') + '\n';
}

function main(argv = process.argv.slice(2)) {
  const opt = (k) => { const a = argv.find((x) => x.startsWith('--' + k + '=')); return a ? a.split('=').slice(1).join('=') : null; };
  const dir = path.resolve(ROOT, opt('dir') || process.env.E2E_ARTIFACT_DIR || 'e2e-artifacts');
  const agg = aggregate(loadArtefacts(dir));
  const md = renderMarkdown(agg, Object.assign(machine(), { generated_at: new Date().toISOString(), source: path.basename(dir) }));
  if (opt('out')) fs.writeFileSync(path.resolve(ROOT, opt('out')), md);
  if (argv.includes('--print') || !opt('out')) process.stdout.write(md);
  return agg;
}

module.exports = { percentile, aggregate, loadArtefacts, renderMarkdown, machine, main, BUDGET };

if (require.main === module) {
  try { main(); } catch (e) { console.error('[perf-baseline] ' + e.message + ' (report only — not failing)'); }
  process.exit(0);
}
