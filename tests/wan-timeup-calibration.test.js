'use strict';
// Meraki "% Time Up" calibration — pure grid + window + CSV helpers (no network).
const test = require('node:test');
const assert = require('node:assert');
const cal = require('../services/wanTimeUpCalibration');

// Synthetic uplink: `n` samples, a fraction with loss `badLoss` and the rest clean.
function series(n, badFrac, badLoss, latency = 40) {
  const out = [];
  for (let i = 0; i < n; i++) out.push({ lossPercent: i / n < badFrac ? badLoss : 0, latencyMs: latency, jitter: 1 });
  return out;
}

test('windowFor: rolling windows end at capturedAt, finest Meraki resolution per span', () => {
  const w = cal.windowFor('Past month', '2026-09-04T00:00:00Z');
  assert.equal(w.window, 'month');
  assert.equal(w.t1 - w.t0, 30 * 86400);
  assert.equal(w.resolution, 3600);
  assert.equal(w.totalIntervals, 720);
  assert.equal(cal.windowFor('Last day', 0).resolution, 60);
  assert.equal(cal.windowFor('week', 0).totalIntervals, 1008);
  assert.throws(() => cal.windowFor('fortnight', 0));
});

test('normalizeUplink: Meraki UI labels → wan ids', () => {
  assert.equal(cal.normalizeUplink('Internet 1'), 'wan1');
  assert.equal(cal.normalizeUplink('Internet 2'), 'wan2');
  assert.equal(cal.normalizeUplink('WAN 2'), 'wan2');
  assert.equal(cal.normalizeUplink('wan1'), 'wan1');
  assert.equal(cal.normalizeUplink('cellular'), null);
});

test('gridSearch recovers a planted per-sample loss rule (loss >= 5 = down)', () => {
  // Ground truth generated by the rule "down iff loss >= 5", missing=down, primary dest.
  const mk = (badFrac, badLoss) => series(720, badFrac, badLoss);
  const truth = (s) => 100 * s.filter(x => x.lossPercent < 5).length / 720;
  const points = [
    { key: 'A wan1 month', series: { primary: mk(0.30, 12), merged: mk(0.30, 12) }, totalIntervals: 720 },   // 70% up
    { key: 'B wan2 month', series: { primary: mk(0.78, 8),  merged: mk(0.78, 8)  }, totalIntervals: 720 },   // 22% up
    { key: 'C wan1 month', series: { primary: mk(0.15, 3),  merged: mk(0.15, 3)  }, totalIntervals: 720 },   // 100% (3 < 5)
    { key: 'D wan1 month', series: { primary: mk(0.02, 100), merged: mk(0.02, 100) }, totalIntervals: 720 }, // 98%
  ];
  points.forEach(p => { p.target = truth(p.series.primary); });
  const { best, combos, note } = cal.gridSearch(points);
  assert.ok(best, 'a best combo exists');
  assert.equal(best.mae, 0, 'planted rule reproduced exactly');
  // The exact cap is identifiable up to the gap between planted loss values (3 < cap <= 8):
  assert.ok(best.lossCap > 3 && best.lossCap <= 8, 'loss cap within the identifiable band: ' + best.lossCap);
  assert.equal(best.latencyCap, null, 'no latency rule needed');
  // A loss<100 rule is clearly worse (points A and B read ~100%).
  const loss100 = combos.find(c => c.lossCap === 100 && c.latencyCap == null && c.missing === 'down' && c.dest === 'primary');
  assert.ok(loss100.mae > 20, 'loss<100 rule mis-scores degraded links by >20 pts');
  assert.ok(typeof note === 'string');
});

test('gridSearch: latency cap identifiable when loss alone cannot explain the target', () => {
  // All samples have ~0 loss but half sit above 300 ms → target 50% only reachable via latency.
  const s = [];
  for (let i = 0; i < 100; i++) s.push({ lossPercent: 0, latencyMs: i < 50 ? 500 : 40, jitter: 1 });
  const { best } = cal.gridSearch([{ key: 'X', target: 50, totalIntervals: 100, series: { primary: s, merged: s } }]);
  assert.ok(best.latencyCap != null && best.latencyCap < 500 && best.latencyCap >= 40, 'latency cap between 40 and 500: ' + best.latencyCap);
  assert.equal(best.mae, 0);
});

test('parseGroundTruthCsv: tolerant headers, Meraki labels, skips unreadable rows', () => {
  const csv = [
    'Site,Period,Label,Loss Rate %,Latency (ms),RTT min (ms),RTT max (ms),Jitter (ms),% Time Up,Source Image,Captured At',
    'Sabodala,Past month,Internet 2,17.58,154.006,0,6370.384,44.596,22.43,image6.png,2026-09-04',
    'Lafigue,Week,Internet 1,0.04,22.635,21.754,112.857,0.353,99.8,image1.png,',
    'Nowhere,Fortnight,Internet 1,0,0,0,0,0,50,x,',
    'Abidjan,Past day,Internet 2,0.04,1.745,1.287,223.177,0.766,100,image9.png,2026-09-04',
  ].join('\n');
  const rows = cal.parseGroundTruthCsv(csv);
  assert.equal(rows.length, 3, 'unknown window row skipped');
  assert.deepEqual(rows[0], { site: 'Sabodala', uplink: 'wan2', window: 'month', target: 22.43, capturedAt: '2026-09-04', loss: 17.58, latency: 154.006, jitter: 44.596 });
  assert.equal(rows[1].capturedAt, null);
  assert.equal(rows[2].uplink, 'wan2');
});
