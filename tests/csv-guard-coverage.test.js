'use strict';
// G-08 — every code path that produces CSV neutralises formula cells (CWE-1236, CG-03).
// A file "produces CSV" when it sets a text/csv type; it must then use public/lib/csvSafe or the
// same inline rule. A CSV upload input (accept=".csv") or a parser is not a producer.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const DIRS = ['', 'routes', 'services', 'public', 'public/lib', 'public/activity-tracker', 'tools/reports'];
const INLINE_RULE = '/^[=+\\-@\\t\\r]/';
// Producers whose cells are all generated by the server (no user text), each with the reason.
const EXEMPT = new Map([
  ['public/reports.html', 'only the static action-items template (fixed sample rows)'],
  ['services/commitmentStore.js', 'accepts CSV as uploaded evidence; produces none'],
]);
// Routes that send CSV built elsewhere: the builder must carry the guard.
const DELEGATES = new Map([
  ['routes/reportStudio.js', 'services/reportPack.js'],
  ['routes/trackers.js', 'services/trackerLegacy.js'],
]);

function files() {
  const out = [];
  for (const d of DIRS) {
    const abs = path.join(ROOT, d);
    if (!fs.existsSync(abs)) continue;
    for (const f of fs.readdirSync(abs)) if (/\.(js|jsx|html)$/.test(f) && !/\.min\./.test(f)) out.push(path.join(d, f));
  }
  return out;
}

test('every CSV producer uses the formula-injection guard', () => {
  const missing = [];
  for (const rel of files()) {
    const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
    if (!/text\/csv/.test(src)) continue;
    if (/^\s*<input[^>]*accept=/m.test(src) && !/new Blob\([^)]*text\/csv|setHeader\([^)]*text\/csv/.test(src)) continue;
    const isGuarded = (t) => t.includes('neutralize') || t.includes(INLINE_RULE);
    const del = DELEGATES.get(rel.replace(/\\/g, '/'));
    const guarded = isGuarded(src) || (del && isGuarded(fs.readFileSync(path.join(ROOT, del), 'utf8')));
    if (!guarded && !EXEMPT.has(rel.replace(/\\/g, '/'))) missing.push(rel);
  }
  assert.deepEqual(missing, [], 'CSV producers without the guard: ' + missing.join(', '));
});

test('the guard neutralises formulas and keeps numbers numeric', () => {
  const { neutralize } = require('../public/lib/csvSafe');
  assert.equal(neutralize('=HYPERLINK("x")'), '\'=HYPERLINK("x")');
  assert.equal(neutralize('@SUM(A1)'), "'@SUM(A1)");
  assert.equal(neutralize('-5'), '-5');
  assert.equal(neutralize('+3.2'), '+3.2');
  assert.equal(neutralize('plain'), 'plain');
});
