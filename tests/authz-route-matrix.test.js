'use strict';
// Step 4 acceptance — per-route authorisation matrix, generated from the live Express router.
// Every /api route must sit behind a session guard (requireReportSession / requireAdmin /
// requireSuperAdmin / requireRole / requireExecutiveOrSuperAdmin) OR be listed in PUBLIC with
// a reason. Routes mounted through express.Router() factories (routes/*.js) are walked too.
// The matrix is written to docs/ops/AUTHZ-MATRIX.md so reviewers see what the gate saw.
const _os = require('os'), _fs = require('fs'), _path = require('path');
for (const k of ['REPORTS_BACKEND', 'TRACKER_BACKEND', 'MEETINGS_BACKEND', 'INSPECTION_BACKEND', 'ASSETS_BACKEND']) process.env[k] = 'sqlite';
process.env.SDP_DATA_DIR = _fs.mkdtempSync(_path.join(_os.tmpdir(), 'authz-'));
process.env.DASH_USER = process.env.DASH_USER || 'authz-admin'; process.env.DASH_PASS = process.env.DASH_PASS || 'authz-pass-0000';
process.env.DASHBOARD_API_KEY = process.env.DASHBOARD_API_KEY || 'authz-key';
for (const k of ['ZOHO_CLIENT_ID', 'ZOHO_CLIENT_SECRET', 'ZOHO_REFRESH_TOKEN']) process.env[k] = process.env[k] || 'dummy';
const { test } = require('node:test');
const assert = require('node:assert');

const GUARDS = ['requireReportSession', 'requireAdmin', 'requireSuperAdmin', 'requireRole', 'requireExecutiveOrSuperAdmin', 'requireEditor', 'requireExecutive'];
// Public by design (reason) + the prefixes behind the global /api gate only. A0: the single source is
// tools/agent/authz-walk.js, shared with the machine-readable docs/ops/authz-matrix.json (tests/authz-matrix-json.test.js).
const { PUBLIC, GLOBAL_GATE_PREFIXES } = require('../tools/agent/authz-walk');

function walk(stack, prefix, out) {
  for (const layer of stack || []) {
    if (layer.route) {
      const methods = Object.keys(layer.route.methods).filter((m) => layer.route.methods[m]).map((m) => m.toUpperCase());
      const names = layer.route.stack.map((l) => l.name || (l.handle && l.handle.name) || 'anonymous');
      const layers = layer.route.stack.map((l) => ({ name: l.name || 'anonymous', handle: l.handle }));
      for (const m of methods) out.push({ key: `${m} ${prefix}${layer.route.path}`, path: prefix + layer.route.path, method: m, mw: names, layers });
    } else if (layer.name === 'router' && layer.handle && layer.handle.stack) {
      const m = layer.regexp && layer.regexp.source.match(/^\^\\\/(.*?)\\\/\?\(\?=\\\/\|\$\)/);
      const sub = m ? '/' + m[1].replace(/\\\//g, '/') : '';
      walk(layer.handle.stack, prefix + sub, out);
    }
  }
}

const walker = require('../tools/agent/authz-walk');
const registry = require('../services/capabilityRegistry');

test('every /api route is guarded, public by declaration, or behind the global gate — matrix written', () => {
  const { app } = require('../server');
  const routes = []; walk(require('../services/routerStack').routerStack(app), '', routes);
  assert.ok(routes.length > 250, `found ${routes.length} routes`);
  const rows = [], unguarded = [];
  for (const r of routes) {
    if (!r.path.startsWith('/api') && r.path !== '/health' && r.path !== '/ready') continue;
    // Every guard on the route, in order (C-02: a role gate behind the session check is visible).
    // C-17: route-local role guards (requireCommittee, requireBuilder…) carry `legacyRoles` and are listed too.
    const guard = r.layers.filter((l) => GUARDS.some((g) => l.name === g || l.name.startsWith(g)) || (l.handle && Array.isArray(l.handle.legacyRoles)))
      .map((l) => (l.handle && Array.isArray(l.handle.legacyRoles) && !l.name.startsWith('requireRole(') ? `${l.name}(${l.handle.legacyRoles.join(' or ')})` : l.name)).join(' + ');
    // C-17: the capability each role guard maps to (services/capabilityRegistry), and the role / site-scope
    // checks made INSIDE the handler (static read of its source, tools/agent/authz-walk.js).
    const caps = walker.guardsOf(r).map((g) => { const c = g.roles && registry.forRoute(r.method, r.path, g.roles); return c ? c.id : 'UNCATALOGUED'; });
    const inl = walker.inlineOf(r);
    let how;
    if (PUBLIC[r.key]) how = `public — ${PUBLIC[r.key]}`;
    else if (guard) how = guard;
    else if (r.path.startsWith('/api/reports/')) { how = 'UNGUARDED'; unguarded.push(r.key); }
    else if (GLOBAL_GATE_PREFIXES.some((p) => r.path.startsWith(p))) how = 'global /api gate (session or page key)';
    else { how = 'UNGUARDED'; unguarded.push(r.key); }
    rows.push({ key: r.key, how, cap: caps.join(' + ') || '—', inline: inl.roles.join(', ') || '—', scope: inl.scope.join(', ') || '—' });
  }
  const md = ['# Authorisation matrix (generated by tests/authz-route-matrix.test.js)', '', `${rows.length} API routes · ${new Date().toISOString().slice(0, 10)}`, '',
    'Columns: **Guard** = every guard middleware on the route (role guards with the roles they admit) · **Capability** = the',
    'catalogued capability each role guard enforces (`services/capabilityRegistry.js`, C-17) · **Inline roles** = roles tested',
    'inside the handler (`userHasRole` / `isAdmin`-style helpers) · **Site scope** = site-narrowing helpers called by the handler.', '',
    '| Route | Guard | Capability | Inline roles | Site scope |', '|---|---|---|---|---|',
    ...rows.sort((a, b) => a.key.localeCompare(b.key)).map((r) => `| \`${r.key}\` | ${r.how} | ${r.cap} | ${r.inline} | ${r.scope} |`), ''].join('\n');
  try { _fs.writeFileSync(_path.join(__dirname, '..', 'docs', 'ops', 'AUTHZ-MATRIX.md'), md); } catch (_) {}
  assert.deepEqual(unguarded, [], 'unguarded API routes:\n' + unguarded.join('\n'));
  const uncat = rows.filter((r) => r.cap.includes('UNCATALOGUED')).map((r) => r.key);
  assert.deepEqual(uncat, [], 'role-guarded routes with no catalogued capability (add it to services/capabilityRegistry.js):\n' + uncat.join('\n'));
});
